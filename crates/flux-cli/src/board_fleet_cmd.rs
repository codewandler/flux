fn validate_board_refs(items: &[String]) -> Result<()> {
    for item in items {
        let Some((board, id)) = item.split_once('/') else {
            bail!("input/schema: fleet item {item:?} must be BOARD/ITEM");
        };
        if board.is_empty() || id.is_empty() {
            bail!("input/schema: fleet item {item:?} must be BOARD/ITEM");
        }
    }
    Ok(())
}
