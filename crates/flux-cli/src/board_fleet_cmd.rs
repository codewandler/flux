fn singleton_doc(
    command: &BoardCommand,
    root: &Path,
    name: &str,
    action: &SingletonDocAction,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let path = root
        .join("docs")
        .join(format!("{}.md", name.to_ascii_uppercase()));
    match action {
        SingletonDocAction::Show => {
            let content = fs::read_to_string(&path)
                .with_context(|| format!("not-found: {name} document at {}", path.display()))?;
            Ok((
                content.clone(),
                json!({"kind":name,"path":display_path(&path),"content":content}),
                vec![],
                None,
            ))
        }
        SingletonDocAction::Set { content, file } => {
            let content = match (content, file) {
                (Some(v), _) => v.clone(),
                (_, Some(v)) => fs::read_to_string(v)?,
                _ => unreachable!(),
            };
            if !command.dry_run {
                fs::create_dir_all(path.parent().unwrap())?;
                fs::write(&path, &content)?;
            }
            Ok((
                format!(
                    "{name} updated{}",
                    if command.dry_run { " (dry run)" } else { "" }
                ),
                json!({"kind":name,"path":display_path(&path),"content":content,"dry_run":command.dry_run}),
                vec![],
                changed_revision(root, command.dry_run)?,
            ))
        }
    }
}

