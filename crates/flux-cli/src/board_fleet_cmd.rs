fn validate_board_common(command: &BoardCommand, request: Option<&Value>) -> Result<()> {
    let mutating = board_action_mutates(&command.action);
    if request.is_some()
        && !matches!(
            command.action,
            BoardAction::Call { .. } | BoardAction::Import { .. }
        )
    {
        bail!("input/schema: --request is supported by `board call` and `board import`; ergonomic command flags and a JSON request cannot be mixed")
    }
    validate_common_options(
        mutating,
        command.dry_run,
        command.idempotency_key.as_deref(),
        command.if_revision.as_deref(),
    )
}

fn validate_fleet_common(command: &FleetCommand, request: Option<&Value>) -> Result<()> {
    let mutating = fleet_action_mutates(&command.action);
    if request.is_some() && !matches!(command.action, FleetAction::Call { .. }) {
        bail!("input/schema: --request is supported by `fleet call`; ergonomic command flags and a JSON request cannot be mixed")
    }
    validate_common_options(
        mutating,
        command.dry_run,
        command.idempotency_key.as_deref(),
        command.if_revision.as_deref(),
    )
}

fn validate_common_options(
    mutating: bool,
    dry_run: bool,
    idempotency_key: Option<&str>,
    if_revision: Option<&str>,
) -> Result<()> {
    if dry_run && !mutating {
        bail!("input/schema: --dry-run is only valid for a mutating operation")
    }
    if let Some(key) = idempotency_key {
        if !mutating {
            bail!("input/schema: --idempotency-key is only valid for a mutating operation")
        }
        if key.trim().is_empty() || key.len() > 128 || key.chars().any(char::is_control) {
            bail!("input/schema: --idempotency-key must be 1..=128 printable characters")
        }
        if dry_run {
            bail!("input/schema: --idempotency-key cannot be combined with --dry-run because a preview is not recorded")
        }
    }
    if let Some(revision) = if_revision {
        if !mutating {
            bail!("input/schema: --if-revision is only valid for a mutating operation")
        }
        if revision.trim().is_empty()
            || revision.len() > 256
            || revision.chars().any(char::is_control)
        {
            bail!("input/schema: --if-revision must be 1..=256 printable characters")
        }
    }
    Ok(())
}

fn request_fingerprint<T: std::fmt::Debug>(action: &T, request: Option<&Value>) -> String {
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    format!("{action:?}").hash(&mut hasher);
    request
        .map(|request| {
            let mut payload = request.clone();
            if let Some(object) = payload.as_object_mut() {
                object.remove("schema");
                object.remove("request_id");
            }
            payload.to_string()
        })
        .hash(&mut hasher);
    format!("{:016x}", hasher.finish())
}

fn board_idempotency_path(root: &Path) -> PathBuf {
    root.join(".flux/board/idempotency.json")
}

fn read_board_idempotency(root: &Path) -> Result<BTreeMap<String, StoredResult>> {
    let path = board_idempotency_path(root);
    if !path.exists() {
        return Ok(BTreeMap::new());
    }
    serde_json::from_str(&fs::read_to_string(path)?)
        .context("validation/gate: invalid board idempotency ledger")
}

fn board_idempotency_hit(
    command: &BoardCommand,
    root: &Path,
    fingerprint: &str,
) -> Result<Option<StoredResult>> {
    let Some(key) = command.idempotency_key.as_deref() else {
        return Ok(None);
    };
    let Some(stored) = read_board_idempotency(root)?.get(key).cloned() else {
        return Ok(None);
    };
    if stored.fingerprint != fingerprint {
        bail!(
            "conflict/precondition: idempotency key was already used for a different board request"
        )
    }
    Ok(Some(stored))
}

fn store_board_idempotency(
    command: &BoardCommand,
    root: &Path,
    stored: StoredResult,
) -> Result<()> {
    if !board_action_mutates(&command.action) || command.dry_run {
        return Ok(());
    }
    let Some(key) = command.idempotency_key.as_ref() else {
        return Ok(());
    };
    let mut records = read_board_idempotency(root)?;
    records.insert(key.clone(), stored);
    let path = board_idempotency_path(root);
    fs::create_dir_all(path.parent().expect("idempotency path has a parent"))?;
    let temp = path.with_extension("json.tmp");
    fs::write(&temp, serde_json::to_vec_pretty(&records)?)?;
    fs::rename(temp, path)?;
    Ok(())
}

