fn render_track(root: &Path, dry_run: bool) -> Result<(String, Value, Vec<String>)> {
    let stories_dir = root.join("docs/stories");
    let board_path = stories_dir.join("README.md");
    if !board_path.is_file() {
        bail!(
            "not-found: no board at {} (run `flux board init --scaffold`)",
            board_path.display()
        );
    }
    let mut warnings = Vec::new();
    let stories = read_stories_with_warnings(root, &mut warnings)?;
    let block = build_track_block(root, &stories);
    let text = fs::read_to_string(&board_path)?;
    let Some(begin) = text.find(BEGIN) else {
        bail!(
            "validation/gate: board {} is missing the marker pair",
            board_path.display()
        );
    };
    let Some(end) = text.find(END) else {
        bail!(
            "validation/gate: board {} is missing the marker pair",
            board_path.display()
        );
    };
    if end < begin {
        bail!("validation/gate: board markers are out of order");
    }
    let i = begin + BEGIN.len();
    let new_text = format!("{}\n{}\n{}", &text[..i], block, &text[end..]);
    let changed = new_text != text;
    if changed && !dry_run {
        fs::write(&board_path, new_text)?;
    }
    let done = stories.iter().filter(|s| s.status == "done").count();
    let human = format!(
        "board {}: {} active story(ies), {} done{}",
        if changed {
            if dry_run {
                "would be rewritten"
            } else {
                "rewritten"
            }
        } else {
            "already current"
        },
        stories.len() - done,
        done,
        if warnings.is_empty() {
            String::new()
        } else {
            format!(" — {} warning(s)", warnings.len())
        }
    );
    Ok((
        human,
        json!({"changed": changed, "dry_run": dry_run, "active": stories.len()-done, "done": done}),
        warnings,
    ))
}

fn read_stories_with_warnings(root: &Path, warnings: &mut Vec<String>) -> Result<Vec<Story>> {
    let dir = root.join("docs/stories");
    if !dir.is_dir() {
        bail!("not-found: no stories directory at {}", dir.display());
    }
    let mut names = fs::read_dir(&dir)?
        .filter_map(|e| e.ok().and_then(|e| e.file_name().into_string().ok()))
        .filter(|name| name.ends_with(".md") && name != "README.md" && name != "_TEMPLATE.md")
        .collect::<Vec<_>>();
    names.sort();
    let mut result = Vec::new();
    let mut seen = BTreeMap::new();
    for name in names {
        let body = fs::read_to_string(dir.join(&name))?;
        let fm = parse_frontmatter(&body);
        if fm.is_empty() {
            warnings.push(format!("{name}: no frontmatter — skipped"));
            continue;
        }
        let (Some(id), Some(title), Some(raw_status)) =
            (fm.get("id"), fm.get("title"), fm.get("status"))
        else {
            warnings.push(format!("{name}: missing id/title/status — skipped"));
            continue;
        };
        let status = normalize_status(raw_status);
        if !STATUSES.contains(&status.as_str()) {
            warnings.push(format!("{name}: unknown status '{raw_status}' — skipped"));
            continue;
        }
        if let Some(previous) = seen.insert(id.clone(), name.clone()) {
            warnings.push(format!("duplicate id '{id}' in {previous} and {name}"));
        }
        let priority = fm.get("priority").and_then(|value| first_integer(value));
        if let Some(raw) = fm.get("priority") {
            if !raw.is_empty() && priority.is_none() {
                warnings.push(format!("{name}: priority '{raw}' has no integer rank"));
            }
        } else if status == "ready" {
            warnings.push(format!("{name}: status 'ready' but no priority"));
        }
        result.push(Story {
            id: id.clone(),
            title: title.clone(),
            status,
            file: name,
            pillar: fm
                .get("pillar")
                .filter(|value| !value.trim().is_empty())
                .cloned(),
            epic: fm
                .get("epic")
                .filter(|value| !value.trim().is_empty())
                .cloned(),
            design: fm
                .get("design")
                .filter(|value| !value.trim().is_empty())
                .cloned(),
            areas: parse_list(fm.get("areas")),
            note: fm
                .get("note")
                .filter(|value| !value.trim().is_empty())
                .cloned(),
            priority,
            dependencies: parse_list(fm.get("depends_on").or_else(|| fm.get("dependencies"))),
            body,
        });
    }
    Ok(result)
}

fn build_track_block(root: &Path, stories: &[Story]) -> String {
    let mut by_status: BTreeMap<&str, Vec<Story>> =
        STATUSES.into_iter().map(|s| (s, Vec::new())).collect();
    for story in stories {
        if let Some(group) = by_status.get_mut(story.status.as_str()) {
            group.push(story.clone());
        }
    }
    for status in ["in-progress", "blocked", "backlog", "done"] {
        by_status
            .get_mut(status)
            .unwrap()
            .sort_by(|a, b| natural_cmp(&a.id, &b.id));
    }
    sort_ready(by_status.get_mut("ready").unwrap());
    let section = |heading: &str, lines: Vec<String>| {
        format!(
            "## {heading}\n{}",
            if lines.is_empty() {
                "_None._".into()
            } else {
                lines.join("\n")
            }
        )
    };
    let now = section(
        "Now (in progress)",
        by_status["in-progress"].iter().map(track_row).collect(),
    );
    let next = section(
        "Next (ready — take the top one unless the user named a story)",
        render_grouped(root, &by_status["ready"]),
    );
    let blocked = section(
        "Blocked",
        by_status["blocked"].iter().map(track_row).collect(),
    );
    let backlog = section("Backlog", render_grouped(root, &by_status["backlog"]));
    let done_rows = by_status["done"].iter().map(track_row).collect::<Vec<_>>();
    let mut done = format!(
        "## Done\n{}",
        if done_rows.is_empty() {
            "_None yet._".into()
        } else {
            done_rows.join("\n")
        }
    );
    if !done_rows.is_empty() {
        done.push_str(
            "\n\n_See [CHANGELOG.md](../../CHANGELOG.md) for the full released history._",
        );
    }
    [
        GENERATED_NOTE.into(),
        String::new(),
        now,
        String::new(),
        next,
        String::new(),
        blocked,
        String::new(),
        backlog,
        String::new(),
        done,
    ]
    .join("\n")
}

fn track_row(story: &Story) -> String {
    let mut parts = vec![format!(
        "- [{} — {}]({})",
        story.id, story.title, story.file
    )];
    if let Some(pillar) = &story.pillar {
        if !pillar.is_empty() {
            parts.push(pillar.clone());
        }
    }
    if let Some(note) = &story.note {
        if !note.is_empty() {
            parts.push(note.clone());
        }
    }
    parts.join(" · ")
}

fn render_grouped(root: &Path, stories: &[Story]) -> Vec<String> {
    let mut out = stories
        .iter()
        .filter(|s| s.epic.is_none())
        .map(track_row)
        .collect::<Vec<_>>();
    let mut grouped: BTreeMap<String, Vec<&Story>> = BTreeMap::new();
    for story in stories {
        if let Some(epic) = &story.epic {
            grouped.entry(epic.clone()).or_default().push(story);
        }
    }
    for (slug, group) in grouped {
        out.push(String::new());
        out.push(format!("### {}", epic_title(root, &slug)));
        if let Some(blurb) = epic_blurb(root, &slug) {
            out.push(format!("_{blurb}_"));
        }
        out.extend(group.into_iter().map(track_row));
    }
    out
}

fn epic_title(root: &Path, slug: &str) -> String {
    if let Ok(text) = fs::read_to_string(root.join("docs/designs").join(format!("{slug}.md"))) {
        if let Some(title) = text
            .lines()
            .map(str::trim)
            .find_map(|line| line.strip_prefix("# "))
        {
            let lower = title.to_ascii_lowercase();
            let title = if lower.starts_with("design:")
                || lower.starts_with("design —")
                || lower.starts_with("design -")
            {
                let rest = title["design".len()..].trim_start();
                rest.char_indices()
                    .next()
                    .filter(|(_, character)| matches!(character, ':' | '—' | '-'))
                    .map(|(index, character)| &rest[index + character.len_utf8()..])
                    .unwrap_or(rest)
            } else {
                title
            };
            return title.trim().into();
        }
    }
    slug.replace(['-', '_'], " ")
        .split_whitespace()
        .map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn epic_blurb(root: &Path, slug: &str) -> Option<String> {
    let text = fs::read_to_string(root.join("docs/designs").join(format!("{slug}.md"))).ok()?;
    let mut why = false;
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.to_ascii_lowercase().starts_with("## why") {
            why = true;
            continue;
        }
        if why && trimmed.starts_with('#') {
            return None;
        }
        if why && !trimmed.is_empty() {
            if trimmed.chars().count() <= 200 {
                return Some(trimmed.into());
            }
            let prefix = trimmed
                .char_indices()
                .take_while(|(i, _)| *i <= 200)
                .map(|(_, c)| c)
                .collect::<String>();
            return Some(format!(
                "{}…",
                prefix.rsplit_once(' ').map(|(a, _)| a).unwrap_or(&prefix)
            ));
        }
    }
    None
}

fn ratio(done: usize, total: usize) -> Value {
    json!({"done": done, "remaining": total.saturating_sub(done), "total": total, "percent": if total == 0 { 0.0 } else { done as f64 * 100.0 / total as f64 }})
}
fn absent_ratio() -> Value {
    json!({"schema": "absent", "done": Value::Null, "remaining": Value::Null, "total": Value::Null, "percent": Value::Null})
}

fn stats(command: &BoardCommand, root: &Path, history: bool, since: Option<&str>) -> Result<Value> {
    let stories = read_board_items(command, root)?;
    let stories_done = stories.iter().filter(|s| s.status == "done").count();
    let mut status = BTreeMap::new();
    for name in STATUSES {
        status.insert(name, stories.iter().filter(|s| s.status == name).count());
    }
    let mut criteria_done = 0;
    let mut criteria_total = 0;
    let mut tasks_done = 0;
    let mut tasks_total = 0;
    let mut task_schema = false;
    for story in &stories {
        let (done, _, total) = checkbox_counts(&story.body, "Acceptance");
        criteria_done += done;
        criteria_total += total;
        let (done, _, total) = checkbox_counts(&story.body, "Tasks");
        tasks_done += done;
        tasks_total += total;
        task_schema |= has_heading(&story.body, "Tasks");
    }
    let epics = stories
        .iter()
        .filter_map(|s| s.epic.as_ref())
        .collect::<BTreeSet<_>>();
    let epic_done = epics
        .iter()
        .filter(|epic| {
            stories
                .iter()
                .filter(|s| s.epic.as_ref() == Some(epic))
                .all(|s| s.status == "done")
        })
        .count();
    let workspace = command.scope == BoardScopeArg::Workspace && command.board.is_none();
    let documents = document_counts(root);
    let (commits, members) = if workspace {
        let config = read_fleet_config(root)?;
        let mut members = BTreeMap::new();
        let mut total = 0usize;
        for repository in &config.repositories {
            let member_root = repository_root(root, repository)?;
            let member_stories = read_stories(&member_root)?;
            let done = member_stories
                .iter()
                .filter(|story| story.status == "done")
                .count();
            let member_commits = canonical_commits(&member_root);
            total += member_commits["total"].as_u64().unwrap_or(0) as usize;
            members.insert(
                repository.id.clone(),
                json!({"stories": ratio(done, member_stories.len()), "canonical_commits": member_commits}),
            );
        }
        (
            json!({"total": total, "members": members.len()}),
            json!(members),
        )
    } else {
        (canonical_commits(root), Value::Null)
    };
    let history_value = if history {
        git_history(root, since)?
    } else {
        Value::Null
    };
    let tasks = if task_schema {
        let mut value = ratio(tasks_done, tasks_total);
        value
            .as_object_mut()
            .unwrap()
            .insert("schema".into(), json!("present"));
        value
    } else {
        absent_ratio()
    };
    let (program_stories, tranche_lanes, waves, program_groups) = if workspace {
        let config = read_fleet_config(root)?;
        (
            ratio(stories_done, stories.len()),
            ratio(
                config.tranches.iter().filter(|group| !group.active).count(),
                config.tranches.len(),
            ),
            ratio(0, config.waves.len()),
            ratio(0, config.groups.len()),
        )
    } else {
        (Value::Null, Value::Null, Value::Null, Value::Null)
    };
    Ok(json!({
        "schema": "flux.board-stats/v1", "epics": ratio(epic_done, epics.len()),
        "stories": ratio(stories_done, stories.len()), "tasks": tasks,
        "criteria": ratio(criteria_done, criteria_total), "acceptance_criteria": ratio(criteria_done, criteria_total),
        "implementation": ratio(stories_done, stories.len()), "status": status,
        "documents": documents, "canonical_commits": commits, "history": history_value,
        "program_stories": program_stories, "tranche_lanes": tranche_lanes,
        "waves": waves, "program_groups": program_groups, "members": members
    }))
}

fn has_heading(text: &str, heading: &str) -> bool {
    text.lines()
        .any(|line| line.trim().eq_ignore_ascii_case(&format!("## {heading}")))
}

fn checkbox_counts(text: &str, heading: &str) -> (usize, usize, usize) {
    let mut in_section = false;
    let mut done = 0;
    let mut total = 0;
    for line in text.lines() {
        let trimmed = line.trim();
        if let Some(found) = trimmed.strip_prefix("## ") {
            in_section = found.trim().eq_ignore_ascii_case(heading);
            continue;
        }
        if in_section && trimmed.starts_with("- [") && trimmed.as_bytes().get(4) == Some(&b']') {
            total += 1;
            if matches!(trimmed.as_bytes().get(3), Some(b'x' | b'X')) {
                done += 1;
            }
        }
    }
    (done, total - done, total)
}

fn document_counts(root: &Path) -> Value {
    let count_md = |path: PathBuf| {
        fs::read_dir(path)
            .ok()
            .into_iter()
            .flatten()
            .filter_map(Result::ok)
            .filter(|e| e.path().extension().and_then(|v| v.to_str()) == Some("md"))
            .count()
    };
    let mut decision_status = BTreeMap::<String, usize>::new();
    for dir in [root.join("docs/decisions"), root.join("decisions")] {
        for decision in decision_records(&dir).unwrap_or_default() {
            let status = decision["status"].as_str().unwrap_or("open").to_string();
            *decision_status.entry(status).or_default() += 1;
        }
    }
    let decisions = decision_status.values().sum::<usize>();
    let designs = count_md(root.join("docs/designs"));
    let linked_designs = read_stories(root)
        .unwrap_or_default()
        .iter()
        .filter(|story| story.design.is_some())
        .count();
    json!({"vision": {"present": singleton_path(root, "vision").is_file() || root.join("VISION.md").is_file()}, "roadmap": {"present": singleton_path(root, "roadmap").is_file() || root.join("ROADMAP.md").is_file()}, "decisions": {"total": decisions, "open": decision_status.get("open").copied().unwrap_or(0), "decided": decision_status.get("decided").copied().unwrap_or(0), "by_status": decision_status}, "designs": {"total": designs, "linked_stories": linked_designs}})
}

fn singleton_path(root: &Path, name: &str) -> PathBuf {
    root.join("docs")
        .join(format!("{}.md", name.to_ascii_uppercase()))
}

fn canonical_commits(root: &Path) -> Value {
    let output = guarded_git(root, &["rev-list", "--count", "HEAD"]);
    let total = output
        .ok()
        .filter(|output| output.exit_code == 0)
        .and_then(|output| output.stdout.trim().parse::<usize>().ok());
    json!({"total": total, "head": git_output(root, &["rev-parse", "HEAD"]), "canonical_ref": git_output(root, &["symbolic-ref", "--quiet", "--short", "refs/remotes/origin/HEAD"])})
}

fn git_output(root: &Path, args: &[&str]) -> Option<String> {
    guarded_git(root, args)
        .ok()
        .filter(|output| output.exit_code == 0)
        .map(|output| output.stdout.trim().into())
}

fn git_history(root: &Path, since: Option<&str>) -> Result<Value> {
    if since.is_some_and(|date| {
        date.len() != 10
            || date
                .chars()
                .enumerate()
                .any(|(index, character)| match index {
                    4 | 7 => character != '-',
                    _ => !character.is_ascii_digit(),
                })
    }) {
        bail!("input/schema: --since must use YYYY-MM-DD")
    }
    let output = guarded_git(
        root,
        &[
            "log",
            "--date=short",
            "--pretty=format:%H%x09%ad",
            "--",
            "docs/stories",
        ],
    );
    let mut days = BTreeMap::<String, (usize, String)>::new();
    if let Ok(output) = output {
        if output.exit_code == 0 {
            // `git log` is newest-first. The first SHA seen for a date is therefore that day's
            // canonical end-of-day snapshot; every row still contributes to the commit count.
            for line in output.stdout.lines() {
                if let Some((commit, date)) = line.split_once('\t') {
                    let entry = days
                        .entry(date.to_string())
                        .or_insert_with(|| (0, commit.to_string()));
                    entry.0 += 1;
                }
            }
        }
    }
    let mut previous = BTreeMap::<String, String>::new();
    let mut result = Vec::new();
    for (date, (commits, commit)) in days {
        let current = story_snapshot_at(root, &commit)?;
        let scope_added = current
            .keys()
            .filter(|id| !previous.contains_key(*id))
            .cloned()
            .collect::<Vec<_>>();
        let scope_removed = previous
            .keys()
            .filter(|id| !current.contains_key(*id))
            .cloned()
            .collect::<Vec<_>>();
        let completed = current
            .iter()
            .filter(|(id, status)| {
                status.as_str() == "done" && previous.get(*id).is_none_or(|before| before != "done")
            })
            .map(|(id, _)| id.clone())
            .collect::<Vec<_>>();
        if since.is_none_or(|minimum| date.as_str() >= minimum) {
            result.push(json!({
                "date": date, "commit": commit, "commits": commits,
                "scope_added": scope_added.len(), "scope_added_items": scope_added,
                "scope_removed": scope_removed.len(), "scope_removed_items": scope_removed,
                "completed": completed.len(), "completed_items": completed,
                "stories": current.len(),
            }));
        }
        previous = current;
    }
    Ok(json!({"schema": "flux.board-history/v1", "since": since, "days": result}))
}

fn story_snapshot_at(root: &Path, commit: &str) -> Result<BTreeMap<String, String>> {
    let output = guarded_git(
        root,
        &["ls-tree", "-r", "--name-only", commit, "--", "docs/stories"],
    )?;
    if output.exit_code != 0 {
        bail!("validation/gate: cannot inspect board history at {commit}")
    }
    let mut snapshot = BTreeMap::new();
    for path in output.stdout.lines() {
        if !path.ends_with(".md") || path.ends_with("/README.md") {
            continue;
        }
        let object = format!("{commit}:{path}");
        let output = guarded_git(root, &["show", &object])?;
        if output.exit_code != 0 {
            bail!("validation/gate: cannot read historical board item {object}")
        }
        let frontmatter = parse_frontmatter(&output.stdout);
        let Some(id) = frontmatter.get("id") else {
            continue;
        };
        snapshot.insert(
            id.clone(),
            frontmatter
                .get("status")
                .cloned()
                .unwrap_or_else(|| "backlog".into()),
        );
    }
    Ok(snapshot)
}

