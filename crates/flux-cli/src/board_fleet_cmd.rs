#[derive(clap::Args, Debug)]
pub(super) struct BoardCommand {
    /// Board root. Repository boards default to the current directory.
    #[arg(long, value_name = "DIR", default_value = ".", global = true)]
    root: PathBuf,
    /// Explicit board binding. Required when more than one compatible board is registered.
    #[arg(long, global = true)]
    board: Option<String>,
    /// Board lifetime/authority scope; independent of profile and backend.
    #[arg(long, value_enum, default_value_t, global = true)]
    scope: BoardScopeArg,
    /// Operation/state-machine profile; independent of scope and backend.
    #[arg(long, value_enum, default_value_t, global = true)]
    profile: BoardProfileArg,
    /// Output encoding. JSON/NDJSON, not human prose, is the automation API.
    #[arg(long, value_enum, default_value_t, global = true)]
    output: AgentOutput,
    /// Read one `flux.cli/v1` JSON request from a file or stdin (`-`).
    #[arg(long, value_name = "FILE|-", global = true)]
    request: Option<String>,
    /// Stable key for retrying a mutating request without applying it twice.
    #[arg(long, global = true)]
    idempotency_key: Option<String>,
    /// Refuse a mutation unless the board still has this revision.
    #[arg(long, global = true)]
    if_revision: Option<String>,
    /// Validate and return the proposed result without writing.
    #[arg(long, global = true)]
    dry_run: bool,
    /// Session board owner when invoked outside a live turn (`last` is accepted).
    #[arg(long, global = true)]
    session: Option<String>,
    #[command(subcommand)]
    action: BoardAction,
}

