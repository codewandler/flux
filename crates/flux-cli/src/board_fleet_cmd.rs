fn read_stories(root: &Path) -> Result<Vec<Story>> {
    let dir = root.join("docs/stories");
    if !dir.is_dir() {
        bail!("not-found: no stories directory at {}", dir.display());
    }
    let mut paths = fs::read_dir(&dir)?
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| {
            path.extension().and_then(|v| v.to_str()) == Some("md")
                && !matches!(
                    path.file_name().and_then(|v| v.to_str()),
                    Some("README.md" | "_TEMPLATE.md")
                )
        })
        .collect::<Vec<_>>();
    paths.sort();
    let mut stories = Vec::new();
    for path in paths {
        let body = fs::read_to_string(&path)?;
        let fm = parse_frontmatter(&body);
        if fm.is_empty() {
            continue;
        }
        let Some(id) = fm.get("id").cloned() else {
            continue;
        };
        let Some(title) = fm.get("title").cloned() else {
            continue;
        };
        let Some(raw_status) = fm.get("status") else {
            continue;
        };
        let status = normalize_status(raw_status);
        if !STATUSES.contains(&status.as_str()) {
            continue;
        }
        stories.push(Story {
            id,
            title,
            status,
            file: path
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .into_owned(),
            pillar: fm.get("pillar").cloned(),
            epic: fm.get("epic").cloned(),
            design: fm.get("design").cloned(),
            areas: parse_list(fm.get("areas")),
            note: fm.get("note").cloned(),
            priority: fm.get("priority").and_then(|v| first_integer(v)),
            dependencies: parse_list(fm.get("depends_on").or_else(|| fm.get("dependencies"))),
            body,
        });
    }
    Ok(stories)
}

fn parse_frontmatter(text: &str) -> BTreeMap<String, String> {
    let mut data = BTreeMap::new();
    let mut lines = text.lines();
    if lines.next().map(str::trim) != Some("---") {
        return data;
    }
    for line in lines {
        if line.trim() == "---" {
            break;
        }
        let Some((key, value)) = line.split_once(':') else {
            continue;
        };
        let key = key.trim();
        let mut value = value.trim();
        if value.len() >= 2
            && ((value.starts_with('"') && value.ends_with('"'))
                || (value.starts_with('\'') && value.ends_with('\'')))
        {
            value = &value[1..value.len() - 1];
        }
        if !key.is_empty() {
            data.insert(key.to_string(), value.to_string());
        }
    }
    data
}

fn normalize_status(value: &str) -> String {
    let mut result = String::new();
    let mut separator = false;
    for ch in value.trim().to_ascii_lowercase().chars() {
        if ch.is_whitespace() || ch == '_' {
            separator = true;
        } else {
            if separator && !result.is_empty() {
                result.push('-');
            }
            separator = false;
            result.push(ch);
        }
    }
    result
}

fn first_integer(value: &str) -> Option<i64> {
    let bytes = value.as_bytes();
    let mut start = None;
    for (i, b) in bytes.iter().enumerate() {
        if b.is_ascii_digit() || (*b == b'-' && bytes.get(i + 1).is_some_and(u8::is_ascii_digit)) {
            start = Some(i);
            break;
        }
    }
    let start = start?;
    let end = bytes[start + usize::from(bytes[start] == b'-')..]
        .iter()
        .position(|b| !b.is_ascii_digit())
        .map(|n| start + usize::from(bytes[start] == b'-') + n)
        .unwrap_or(bytes.len());
    value[start..end].parse().ok()
}

fn parse_list(value: Option<&String>) -> Vec<String> {
    let Some(value) = value else {
        return vec![];
    };
    value
        .trim()
        .trim_start_matches('[')
        .trim_end_matches(']')
        .split(',')
        .map(|part| part.trim().trim_matches(['\'', '"']).to_string())
        .filter(|s| !s.is_empty())
        .collect()
}

fn natural_cmp(a: &str, b: &str) -> CmpOrdering {
    fn parts(value: &str) -> (String, i64, String) {
        let prefix = value
            .chars()
            .take_while(|c| c.is_ascii_alphabetic())
            .collect::<String>()
            .to_ascii_uppercase();
        let rest = &value[prefix.len()..];
        let number = rest
            .trim_start_matches(['-', '_', ' '])
            .chars()
            .take_while(|c| c.is_ascii_digit())
            .collect::<String>()
            .parse()
            .unwrap_or(0);
        (
            if prefix.is_empty() {
                "~".into()
            } else {
                prefix
            },
            number,
            value.into(),
        )
    }
    parts(a).cmp(&parts(b))
}

fn sort_ready(stories: &mut [Story]) {
    stories.sort_by(|a, b| {
        a.priority
            .unwrap_or(i64::MAX)
            .cmp(&b.priority.unwrap_or(i64::MAX))
            .then_with(|| natural_cmp(&a.id, &b.id))
    });
}

fn item_result(mut stories: Vec<Story>) -> Result<(String, Value, Vec<String>, Option<String>)> {
    stories.sort_by(|a, b| natural_cmp(&a.id, &b.id));
    let human = stories
        .iter()
        .map(|s| format!("{}\t{}\t{}", s.id, s.status, s.title))
        .collect::<Vec<_>>()
        .join("\n");
    Ok((human, json!({"items": stories}), vec![], None))
}

