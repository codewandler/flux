fn emit(
    output: AgentOutput,
    human: &str,
    data: Value,
    warnings: Vec<String>,
    revision: Option<&str>,
    request_id: Option<&str>,
) -> Result<()> {
    // Redaction is the last shared boundary before every renderer. Individual producers still
    // redact before persistence, but keeping this guard here prevents a new command from leaking a
    // credential/path simply because its author remembered JSON and forgot human or NDJSON output.
    let human = redact(human);
    let data = redact_value(data);
    let warnings = warnings
        .into_iter()
        .map(|warning| redact(&warning))
        .collect::<Vec<_>>();
    match output {
        AgentOutput::Human => {
            if !human.is_empty() {
                println!("{human}");
            }
            for warning in warnings {
                eprintln!("warning: {warning}");
            }
        }
        AgentOutput::Json => println!(
            "{}",
            serde_json::to_string_pretty(&json!({
                "schema": CLI_SCHEMA, "ok": true, "request_id": request_id,
                "revision": revision, "data": data, "warnings": warnings, "error": Value::Null
            }))?
        ),
        AgentOutput::Ndjson => {
            if !data.is_null() {
                println!(
                    "{}",
                    serde_json::to_string(&json!({
                        "schema": CLI_SCHEMA, "ok": true, "request_id": request_id,
                        "revision": revision, "data": data, "warnings": warnings, "error": Value::Null
                    }))?
                );
            }
        }
    }
    Ok(())
}

fn emit_error(output: AgentOutput, error: anyhow::Error) -> Result<()> {
    let message = format!("{error:#}");
    if output == AgentOutput::Human {
        return Err(error);
    }
    let (class, code) = error_class(&message);
    let envelope = json!({
        "schema": CLI_SCHEMA, "ok": false, "request_id": Value::Null, "revision": Value::Null,
        "data": Value::Null, "warnings": [], "error": {"class": class, "code": code, "message": redact(&message)}
    });
    println!("{}", serde_json::to_string_pretty(&envelope)?);
    std::process::exit(code);
}

fn error_class(message: &str) -> (&'static str, i32) {
    for (prefix, code) in [
        ("input/schema", 2),
        ("not-found", 3),
        ("conflict/precondition", 4),
        ("permission", 5),
        ("transient-worker", 6),
        ("validation/gate", 7),
    ] {
        if message.starts_with(prefix) {
            return (prefix, code);
        }
    }
    ("validation/gate", 7)
}

fn load_request(path: Option<&str>) -> Result<Option<Value>> {
    let Some(path) = path else {
        return Ok(None);
    };
    let mut text = String::new();
    if path == "-" {
        io::stdin().read_to_string(&mut text)?;
    } else {
        text = fs::read_to_string(path)
            .with_context(|| format!("input/schema: read request {path}"))?;
    }
    let value: Value =
        serde_json::from_str(&text).context("input/schema: request is not valid JSON")?;
    if !value.is_object() {
        bail!("input/schema: request must be a JSON object");
    }
    Ok(Some(value))
}

fn request_id_from(request: Option<&Value>) -> Result<Option<String>> {
    let Some(value) = request.and_then(|request| request.get("request_id")) else {
        return Ok(None);
    };
    let id = value
        .as_str()
        .context("input/schema: request_id must be a string")?;
    if id.is_empty() || id.len() > 128 || id.chars().any(char::is_control) {
        bail!("input/schema: request_id must be 1..=128 printable characters")
    }
    Ok(Some(id.to_string()))
}

fn confined_root(root: &Path) -> Result<PathBuf> {
    let current = std::env::current_dir()?;
    let candidate = if root.is_absolute() {
        root.to_path_buf()
    } else {
        current.join(root)
    };
    candidate
        .canonicalize()
        .with_context(|| format!("not-found: board/fleet root {}", candidate.display()))
}

