fn read_fleet_state(root: &Path) -> Result<FleetState> {
    let path = root.join(".flux/fleet/state.json");
    if !path.exists() {
        return Ok(FleetState::default());
    }
    let state: FleetState = serde_json::from_str(&fs::read_to_string(path)?)
        .context("validation/gate: invalid durable fleet state")?;
    validate_fleet_state(&state)?;
    Ok(state)
}

fn validate_fleet_state(state: &FleetState) -> Result<()> {
    if state.main_agent.id != "main" || state.main_agent.role != "coordinator" {
        bail!("validation/gate: fleet state must contain exactly one `main` coordinator")
    }
    if state.agents.contains_key("main")
        || state
            .agents
            .values()
            .any(|agent| agent.get("role").and_then(Value::as_str) == Some("coordinator"))
    {
        bail!("validation/gate: worker registry cannot contain another coordinator")
    }
    Ok(())
}

fn read_fleet_config(root: &Path) -> Result<FleetConfig> {
    let path = root.join(".flux/fleet.toml");
    let text = fs::read_to_string(&path)
        .with_context(|| format!("not-found: fleet configuration {}", path.display()))?;
    let config: FleetConfig = toml::from_str(&text)
        .with_context(|| format!("input/schema: invalid {}", path.display()))?;
    if config.schema != "flux.fleet/v1" {
        bail!(
            "input/schema: fleet schema must be `flux.fleet/v1`, got {:?}",
            config.schema
        )
    }
    validate_fleet_limits(config.max_workers, config.max_wave, config.max_rework)?;
    if !config.worktree_root.is_absolute()
        && config
            .worktree_root
            .components()
            .any(|component| matches!(component, std::path::Component::ParentDir))
    {
        bail!("permission: relative worktree_root cannot escape the fleet root")
    }
    let mut ids = BTreeSet::new();
    let mut roots: Vec<(String, PathBuf)> = Vec::new();
    for repository in &config.repositories {
        flux_datasource::board::BoardId::new(&repository.id)
            .map_err(|error| anyhow::anyhow!("input/schema: repository {error}"))?;
        flux_datasource::board::BoardId::new(&repository.board)
            .map_err(|error| anyhow::anyhow!("input/schema: board {error}"))?;
        if !ids.insert(repository.id.clone()) {
            bail!(
                "conflict/precondition: duplicate fleet repository id {:?}",
                repository.id
            )
        }
        if repository.gate.is_empty() {
            bail!(
                "validation/gate: repository {} has no final gate argv",
                repository.id
            )
        }
        let path = if repository.root.is_absolute() {
            repository.root.clone()
        } else {
            root.join(&repository.root)
        };
        let canonical = path.canonicalize().with_context(|| {
            format!(
                "not-found: repository {} root {}",
                repository.id,
                path.display()
            )
        })?;
        for (other_id, other) in &roots {
            if canonical.starts_with(other) || other.starts_with(&canonical) {
                bail!(
                    "conflict/precondition: repository roots overlap: {} and {}",
                    other_id,
                    repository.id
                )
            }
        }
        roots.push((repository.id.clone(), canonical));
    }
    if let Some(instructions) = &config.main.instructions {
        confined_config_file(root, instructions, "main instructions")?;
    }
    let mut template_ids = BTreeSet::new();
    for template in &config.agent_templates {
        flux_datasource::board::BoardId::new(&template.id)
            .map_err(|error| anyhow::anyhow!("input/schema: agent template {error}"))?;
        if template.id == "main" || !template_ids.insert(&template.id) {
            bail!(
                "conflict/precondition: duplicate or reserved agent template id {:?}",
                template.id
            )
        }
        if template.role.trim().is_empty() {
            bail!(
                "input/schema: agent template {} has an empty role",
                template.id
            )
        }
        if !(1..=config.max_workers).contains(&template.max_instances) {
            bail!(
                "input/schema: agent template {} max_instances must be 1..={} ",
                template.id,
                config.max_workers
            )
        }
        confined_config_file(
            root,
            &template.instructions,
            &format!("agent template {} instructions", template.id),
        )?;
    }
    validate_schedule_groups(&config.tranches, "tranche", usize::MAX)?;
    validate_schedule_groups(&config.waves, "wave", 10)?;
    validate_schedule_groups(&config.groups, "group", usize::MAX)?;
    Ok(config)
}

fn confined_config_file(root: &Path, path: &Path, label: &str) -> Result<PathBuf> {
    let candidate = if path.is_absolute() {
        path.to_path_buf()
    } else {
        root.join(path)
    };
    let canonical = candidate
        .canonicalize()
        .with_context(|| format!("not-found: {label} at {}", candidate.display()))?;
    if !canonical.starts_with(root) || !canonical.is_file() {
        bail!(
            "permission: {label} must be a file confined under {}",
            root.display()
        )
    }
    Ok(canonical)
}

fn validate_schedule_groups(groups: &[ScheduleGroup], kind: &str, cap: usize) -> Result<()> {
    let mut ids = BTreeSet::new();
    for group in groups {
        if !ids.insert(&group.id) {
            bail!("conflict/precondition: duplicate {kind} id {:?}", group.id)
        }
        if group.items.len() > cap {
            bail!(
                "validation/gate: {kind} {} has {} items, maximum is {cap}",
                group.id,
                group.items.len()
            )
        }
    }
    let active = groups.iter().filter(|group| group.active).count();
    if kind == "tranche" && active > 1 {
        bail!("validation/gate: exactly zero or one tranche may be active, found {active}")
    }
    Ok(())
}

fn repository_root(workspace: &Path, repository: &FleetRepository) -> Result<PathBuf> {
    let path = if repository.root.is_absolute() {
        repository.root.clone()
    } else {
        workspace.join(&repository.root)
    };
    path.canonicalize().with_context(|| {
        format!(
            "not-found: repository {} root {}",
            repository.id,
            path.display()
        )
    })
}

fn member_root(workspace: &Path, member: &str) -> Result<PathBuf> {
    let config = read_fleet_config(workspace)?;
    let repository = config
        .repositories
        .iter()
        .find(|repository| repository.id == member || repository.board == member)
        .with_context(|| format!("not-found: workspace board member {member}"))?;
    repository_root(workspace, repository)
}

fn workspace_stories(workspace: &Path) -> Result<Vec<Story>> {
    let config = read_fleet_config(workspace)?;
    let mut result = Vec::new();
    for repository in &config.repositories {
        let root = repository_root(workspace, repository)?;
        for mut story in read_stories(&root)? {
            story.dependencies = story
                .dependencies
                .into_iter()
                .map(|dependency| {
                    if dependency.contains('/') {
                        dependency
                    } else {
                        format!("{}/{}", repository.id, dependency)
                    }
                })
                .collect();
            story.id = format!("{}/{}", repository.id, story.id);
            story.file = format!("{}/docs/stories/{}", repository.id, story.file);
            result.push(story);
        }
    }
    result.sort_by(|a, b| a.id.cmp(&b.id));
    validate_workspace_dependencies(&result)?;
    Ok(result)
}

fn validate_workspace_dependencies(stories: &[Story]) -> Result<()> {
    let ids = stories
        .iter()
        .map(|story| story.id.as_str())
        .collect::<BTreeSet<_>>();
    for story in stories {
        for dependency in &story.dependencies {
            if !ids.contains(dependency.as_str()) {
                bail!(
                    "validation/gate: {} depends on missing workspace item {}",
                    story.id,
                    dependency
                )
            }
        }
    }
    fn visit<'a>(
        id: &'a str,
        by_id: &BTreeMap<&'a str, &'a Story>,
        visiting: &mut Vec<&'a str>,
        visited: &mut BTreeSet<&'a str>,
    ) -> Result<()> {
        if let Some(position) = visiting.iter().position(|candidate| *candidate == id) {
            let mut cycle = visiting[position..].to_vec();
            cycle.push(id);
            bail!(
                "validation/gate: workspace dependency cycle: {}",
                cycle.join(" -> ")
            )
        }
        if !visited.insert(id) {
            return Ok(());
        }
        visiting.push(id);
        if let Some(story) = by_id.get(id) {
            for dependency in &story.dependencies {
                visit(dependency, by_id, visiting, visited)?;
            }
        }
        visiting.pop();
        Ok(())
    }
    let by_id = stories
        .iter()
        .map(|story| (story.id.as_str(), story))
        .collect::<BTreeMap<_, _>>();
    let mut visited = BTreeSet::new();
    for id in by_id.keys().copied() {
        visit(id, &by_id, &mut Vec::new(), &mut visited)?;
    }
    Ok(())
}
