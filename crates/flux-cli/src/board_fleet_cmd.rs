fn emit(
    output: AgentOutput,
    human: &str,
    data: Value,
    warnings: Vec<String>,
    revision: Option<&str>,
) -> Result<()> {
    match output {
        AgentOutput::Human => {
            if !human.is_empty() {
                println!("{human}");
            }
            for warning in warnings {
                eprintln!("warning: {warning}");
            }
        }
        AgentOutput::Json => println!(
            "{}",
            serde_json::to_string_pretty(&json!({
                "schema": CLI_SCHEMA, "ok": true, "request_id": Value::Null,
                "revision": revision, "data": data, "warnings": warnings, "error": Value::Null
            }))?
        ),
        AgentOutput::Ndjson => {
            if !data.is_null() {
                println!(
                    "{}",
                    serde_json::to_string(&json!({
                        "schema": CLI_SCHEMA, "ok": true, "request_id": Value::Null,
                        "revision": revision, "data": data, "warnings": warnings, "error": Value::Null
                    }))?
                );
            }
        }
    }
    Ok(())
}

fn emit_error(output: AgentOutput, error: anyhow::Error) -> Result<()> {
    let message = format!("{error:#}");
    if output == AgentOutput::Human {
        return Err(error);
    }
    let (class, code) = error_class(&message);
    let envelope = json!({
        "schema": CLI_SCHEMA, "ok": false, "request_id": Value::Null, "revision": Value::Null,
        "data": Value::Null, "warnings": [], "error": {"class": class, "code": code, "message": redact(&message)}
    });
    println!("{}", serde_json::to_string_pretty(&envelope)?);
    std::process::exit(code);
}

fn error_class(message: &str) -> (&'static str, i32) {
    for (prefix, code) in [
        ("input/schema", 2),
        ("not-found", 3),
        ("conflict/precondition", 4),
        ("permission", 5),
        ("transient-worker", 6),
        ("validation/gate", 7),
    ] {
        if message.starts_with(prefix) {
            return (prefix, code);
        }
    }
    ("validation/gate", 7)
}

fn load_request(path: Option<&str>) -> Result<Option<Value>> {
    let Some(path) = path else {
        return Ok(None);
    };
    let mut text = String::new();
    if path == "-" {
        io::stdin().read_to_string(&mut text)?;
    } else {
        text = fs::read_to_string(path)
            .with_context(|| format!("input/schema: read request {path}"))?;
    }
    let value: Value =
        serde_json::from_str(&text).context("input/schema: request is not valid JSON")?;
    if !value.is_object() {
        bail!("input/schema: request must be a JSON object");
    }
    Ok(Some(value))
}

