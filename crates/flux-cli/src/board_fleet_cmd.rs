const DEFAULT_STORY_CAPABILITIES: [&str; 4] = ["read", "edit", "git", "shell"];
const REQUIRED_WRITER_CAPABILITIES: [&str; 3] = ["read", "edit", "git"];
const AGENT_LOOP_MACHINERY_OPERATIONS: [&str; 9] = [
    "detect_intent",
    "explore",
    "approve_batch",
    "execute_batch",
    "present_results",
    "ai_segment",
    "observe",
    "evidence",
    "metrics",
];

fn capability_operations(name: &str) -> Option<&'static [&'static str]> {
    Some(match name {
        "read" => &[
            "read",
            "glob",
            "grep",
            "search",
            "get",
            "list",
            "sources",
            "batch_get",
            "relation",
            "cwd",
            "home_dir",
            "sys_info",
            "now",
        ],
        "edit" => &["write", "edit", "append", "patch"],
        "git-read" => &["git_status", "git_diff", "git_log", "git_hunks"],
        // A story writer may inspect, stage and commit its own result. Integration, checkout,
        // worktree mutation, revert and push remain coordinator operations, not worker tools.
        "git" => &[
            "git_status",
            "git_diff",
            "git_log",
            "git_hunks",
            "git_stage",
            "git_stage_hunks",
            "git_unstage",
            "git_commit",
            "git_branch",
        ],
        "shell" => &["bash", "proc.run"],
        "rust" => &[
            "cargo_check",
            "cargo_build",
            "cargo_test",
            "cargo_clippy",
            "cargo_fmt",
        ],
        "node" => &["npm", "node_run"],
        "go" => &["go_build", "go_test", "go_vet"],
        "python" => &["python_run", "pytest"],
        "make" => &["make"],
        "task" => &["task"],
        _ => return None,
    })
}

fn normalize_worker_capabilities(
    mode: FleetTaskMode,
    requested: &[String],
) -> Result<(Vec<String>, Vec<String>)> {
    let mut capabilities = requested
        .iter()
        .map(|capability| capability.trim().to_ascii_lowercase())
        .filter(|capability| !capability.is_empty())
        .collect::<Vec<_>>();
    capabilities.sort();
    capabilities.dedup();

    let required: &[&str] = match mode {
        FleetTaskMode::ReadOnly => &["read"],
        FleetTaskMode::Write => &REQUIRED_WRITER_CAPABILITIES,
    };
    let mut missing = required
        .iter()
        .filter(|required| !capabilities.iter().any(|found| found == **required))
        .map(|required| (*required).to_string())
        .collect::<Vec<_>>();
    for capability in &capabilities {
        let invalid_for_mode =
            mode == FleetTaskMode::ReadOnly && !matches!(capability.as_str(), "read" | "git-read");
        if invalid_for_mode || capability_operations(capability).is_none() {
            missing.push(capability.clone());
        }
    }
    missing.sort();
    missing.dedup();
    if !missing.is_empty() {
        bail!(
            "validation/gate: missing required capabilities: {}",
            missing.join(", ")
        )
    }

    let mut operations = capabilities
        .iter()
        .flat_map(|capability| capability_operations(capability).unwrap_or_default())
        .map(|operation| (*operation).to_string())
        .collect::<Vec<_>>();
    operations.extend(
        AGENT_LOOP_MACHINERY_OPERATIONS
            .iter()
            .map(|operation| (*operation).to_string()),
    );
    operations.sort();
    operations.dedup();
    Ok((capabilities, operations))
}

fn normalize_fences(fences: impl IntoIterator<Item = String>) -> Vec<String> {
    let mut fences = [".git/**".to_string(), ".flux/fleet/**".to_string()]
        .into_iter()
        .chain(fences)
        .map(|fence| fence.trim().trim_start_matches("./").to_string())
        .filter(|fence| !fence.is_empty())
        .collect::<Vec<_>>();
    fences.sort();
    fences.dedup();
    fences
}

fn capability_set_manifest(
    mode: FleetTaskMode,
    capabilities: &[String],
    operations: &[String],
    writable_root: &Path,
    read_roots: &[PathBuf],
    fences: &[String],
) -> Value {
    let projection = json!({
        "schema": "flux.fleet-capability-set/v1",
        "mode": mode,
        "capabilities": capabilities,
        "operations": operations,
        "writable_root": display_path(writable_root),
        "read_roots": read_roots.iter().map(|root| display_path(root)).collect::<Vec<_>>(),
        "fences": fences,
    });
    let encoded =
        serde_json::to_string(&projection).expect("capability-set projection is JSON serializable");
    json!({
        "schema": "flux.fleet-capability-set/v1",
        "digest_sha256": flux_lang::runtime::sha256_hex(&encoded),
        "mode": mode,
        "capability_count": capabilities.len(),
        "operation_count": operations.len(),
        "read_root_count": read_roots.len(),
        "fence_count": fences.len(),
        "writable_root_sha256": flux_lang::runtime::sha256_hex(&display_path(writable_root)),
    })
}

fn value_string_list(value: &Value, key: &str, agent: &str) -> Result<Vec<String>> {
    value[key]
        .as_array()
        .with_context(|| format!("validation/gate: admitted agent {agent} has no {key} snapshot"))?
        .iter()
        .map(|entry| {
            entry.as_str().map(str::to_string).with_context(|| {
                format!("validation/gate: admitted agent {agent} has a non-string {key} entry")
            })
        })
        .collect()
}

fn agent_context_origin(
    id: &str,
    instructions: &str,
    assignment: Option<&Value>,
    resume: bool,
    goals_revision: u64,
) -> Value {
    let session_mode = if resume { "continue" } else { "fresh" };
    if id == "main" {
        return json!({
            "schema": "flux.fleet-context-origin/v1",
            "kind": "main-coordinator",
            "agent": "main",
            "session_mode": session_mode,
            "goals_revision": goals_revision,
        });
    }
    let assignment = assignment.cloned().unwrap_or_else(|| json!({}));
    let assignment_projection = json!({
        "board_ref": assignment["board_ref"],
        "repository": assignment["repository"],
        "wave": assignment["wave"],
        "branch": assignment["branch"],
        "base_commit": assignment["base_commit"],
        "worktree": assignment["worktree"],
    });
    let assignment_json = serde_json::to_string(&assignment_projection)
        .expect("assignment context projection is JSON serializable");
    json!({
        "schema": "flux.fleet-context-origin/v1",
        "kind": if assignment_projection["board_ref"].is_string() {
            "story-assignment"
        } else {
            "admitted-worker"
        },
        "agent": id,
        "board_ref": assignment_projection["board_ref"],
        "session_mode": session_mode,
        "assignment_sha256": flux_lang::runtime::sha256_hex(&assignment_json),
        "worker_contract_sha256": flux_lang::runtime::sha256_hex(instructions.trim()),
    })
}

fn read_configured_instructions(root: &Path, path: &Path, label: &str) -> Result<String> {
    let absolute = confined_config_file(root, path, label)?;
    let relative = absolute
        .strip_prefix(root)
        .with_context(|| format!("permission: {label} escaped the fleet root"))?;
    let relative = relative
        .to_str()
        .with_context(|| format!("input/schema: {label} path is not UTF-8"))?;
    guarded_system(root)?
        .read_optional_text(relative)?
        .with_context(|| format!("not-found: {label} {}", absolute.display()))
}

fn story_worker_request(item: &str, assignment: &Value, worktree: &Path) -> String {
    format!(
        "Work only on board item {item}. Your isolated worktree is {}. Your branch is {} at pinned base {}. Use `flux board skill`, then inspect the owning repository's AGENTS.md, the exact story contract and linked design. Implement that contract as a writer; do not select, observe or explore unrelated work. Finish with one exact commit and report its full SHA, observed write set, targeted test argv, failing-before/passing-after evidence, and summary for `flux fleet handoff`.",
        display_path(worktree),
        assignment["branch"].as_str().unwrap_or("unknown"),
        assignment["base_commit"].as_str().unwrap_or("unknown"),
    )
}

fn main_turn_spec(root: &Path, state: &FleetState, request: String) -> Result<AgentTurnSpec> {
    let config = read_fleet_config(root)?;
    let read_roots = config
        .repositories
        .iter()
        .map(|repository| repository_root(root, repository))
        .collect::<Result<Vec<_>>>()?;
    let instructions = match config.main.instructions.as_deref() {
        Some(path) => read_configured_instructions(root, path, "main coordinator instructions")?,
        None => "You are the fleet's only main coordinator. Ingest requirements and agent follow-ups, keep planning authority on the board, schedule only dependency-satisfied work, and never push, publish, deploy, or delete worktrees.".into(),
    };
    let resume = state.main_agent.session.is_some();
    let context_origin = agent_context_origin(
        "main",
        &instructions,
        None,
        resume,
        state.main_agent.goals_revision,
    );
    Ok(AgentTurnSpec {
        id: "main".into(),
        worktree: root.to_path_buf(),
        read_roots,
        store: agent_store_path(root, "main")?,
        model: config.main.model,
        instructions,
        request,
        resume,
        enforce_operation_ceiling: false,
        admitted_operations: Vec::new(),
        capability_set: Value::Null,
        shell_capability: false,
        context_origin,
    })
}

fn addressed_turn_spec(
    root: &Path,
    state: &FleetState,
    target: &str,
    request: String,
) -> Result<AgentTurnSpec> {
    if target == "main" {
        return main_turn_spec(root, state, request);
    }
    let agent = state
        .agents
        .get(target)
        .with_context(|| format!("not-found: admitted fleet agent {target}"))?;
    if matches!(
        agent["status"].as_str(),
        Some("cancelled" | "parked" | "failed")
    ) {
        bail!("conflict/precondition: agent {target} is not available for delivery")
    }
    let worktree = agent["assignment"]["worktree"]
        .as_str()
        .map(PathBuf::from)
        .unwrap_or_else(|| root.to_path_buf());
    let writable_root = agent["writable_root"].as_str().with_context(|| {
        format!("validation/gate: admitted agent {target} has no writable-root snapshot")
    })?;
    if Path::new(writable_root) != worktree {
        bail!(
            "validation/gate: admitted agent {target} writable root drifted; explicit re-admission is required"
        )
    }
    let read_roots = value_string_list(agent, "read_roots", target)?
        .into_iter()
        .map(PathBuf::from)
        .collect::<Vec<_>>();
    let instructions = agent["instructions"]
        .as_str()
        .with_context(|| {
            format!("validation/gate: admitted agent {target} has no instruction snapshot")
        })?
        .to_string();
    let mode: FleetTaskMode = serde_json::from_value(agent["mode"].clone()).with_context(|| {
        format!("validation/gate: admitted agent {target} has no valid mode snapshot")
    })?;
    let configured_capabilities = value_string_list(agent, "capabilities", target)?;
    let (capabilities, admitted_operations) =
        normalize_worker_capabilities(mode, &configured_capabilities)?;
    let fences = normalize_fences(value_string_list(agent, "fences", target)?);
    let capability_set = capability_set_manifest(
        mode,
        &capabilities,
        &admitted_operations,
        &worktree,
        &read_roots,
        &fences,
    );
    let admitted_digest = agent["capability_set"]["digest_sha256"]
        .as_str()
        .with_context(|| {
            format!("validation/gate: admitted agent {target} has no capability-set digest")
        })?;
    if capability_set["digest_sha256"].as_str() != Some(admitted_digest) {
        bail!(
            "validation/gate: admitted agent {target} capability-set digest drifted; explicit re-admission is required"
        )
    }
    let resume = agent["runtime_session"].is_string();
    let context_origin = agent_context_origin(
        target,
        &instructions,
        agent.get("assignment"),
        resume,
        state.main_agent.goals_revision,
    );
    Ok(AgentTurnSpec {
        id: target.to_string(),
        store: agent_store_path(&worktree, target)?,
        worktree,
        read_roots,
        model: agent["model"].as_str().map(str::to_string),
        instructions,
        request,
        resume,
        enforce_operation_ceiling: true,
        shell_capability: capabilities.iter().any(|capability| capability == "shell"),
        admitted_operations,
        capability_set,
        context_origin,
    })
}

fn agent_store_path(worktree: &Path, id: &str) -> Result<PathBuf> {
    let segment = safe_ref_segment(id);
    let logical = format!("flux-fleet/sessions/{segment}");
    if let Some(path) = git_output(
        worktree,
        &[
            "rev-parse",
            "--path-format=absolute",
            "--git-path",
            &logical,
        ],
    ) {
        return Ok(PathBuf::from(path));
    }
    Ok(worktree.join(".flux/fleet/sessions").join(segment))
}

fn scoped_goals(state: &FleetState) -> String {
    if state.goals.is_empty() {
        return "(no scoped goals recorded)".into();
    }
    state
        .goals
        .iter()
        .map(|(key, goal)| format!("- {key}: {}", goal.statement))
        .collect::<Vec<_>>()
        .join("\n")
}

const FLEET_AGENT_EVENT_LIMIT: usize = 256 * 1024;

#[derive(Deserialize)]
struct OversizedFleetEventHeader {
    #[serde(rename = "type")]
    kind: String,
    v: Option<Value>,
    session: Option<String>,
    outcome: Option<String>,
    usage: Option<Value>,
    cost_usd: Option<Value>,
}

fn summarize_oversized_fleet_event(line: &str, actual_bytes: usize, limit_bytes: usize) -> Value {
    let header = serde_json::from_str::<OversizedFleetEventHeader>(line).ok();
    let sha256 = flux_lang::runtime::sha256_hex(line);
    if header
        .as_ref()
        .is_some_and(|header| header.kind == "turn_end")
    {
        let header = header.expect("turn_end header checked above");
        return json!({
            "type": "turn_end",
            "v": header.v,
            "session": header.session,
            "outcome": header.outcome,
            "usage": header.usage,
            "cost_usd": header.cost_usd,
            "answer": "",
            "error": "omitted: event_too_large",
            "payload_omitted": {
                "reason": "event_too_large",
                "actual_bytes": actual_bytes,
                "limit_bytes": limit_bytes,
                "sha256": sha256,
            },
        });
    }
    json!({
        "type": "fleet_event_omitted",
        "original_type": header.map(|header| header.kind),
        "reason": "event_too_large",
        "actual_bytes": actual_bytes,
        "limit_bytes": limit_bytes,
        "sha256": sha256,
    })
}

fn parse_fleet_agent_events(
    stdout: &str,
    agent_id: &str,
    event_limit: usize,
) -> Result<(Vec<Value>, Option<String>, Value, Value)> {
    let mut events = Vec::new();
    let mut session = None;
    let mut terminal = None;
    let mut event_count = 0usize;
    let mut total_event_bytes = 0usize;
    let mut largest_event_bytes = 0usize;
    let mut omitted_event_count = 0usize;
    for line in stdout.lines() {
        let actual_bytes = line.len();
        event_count += 1;
        total_event_bytes += actual_bytes;
        largest_event_bytes = largest_event_bytes.max(actual_bytes);
        let mut event = if actual_bytes > event_limit {
            omitted_event_count += 1;
            summarize_oversized_fleet_event(line, actual_bytes, event_limit)
        } else {
            serde_json::from_str(line).with_context(|| {
                format!("transient-worker: agent {agent_id} emitted malformed stream JSON")
            })?
        };
        if let Some(value) = event.get("session").and_then(Value::as_str) {
            session = Some(value.to_string());
        }
        if event["type"].as_str() == Some("turn_start") {
            event.as_object_mut().map(|object| object.remove("input"));
        }
        if event["type"].as_str() == Some("turn_end") {
            terminal = Some(event.clone());
        }
        events.push(event);
    }
    let terminal = terminal.with_context(|| {
        format!("transient-worker: agent {agent_id} ended without a terminal turn event")
    })?;
    let stream_budget = json!({
        "schema": "flux.fleet-agent-stream-budget/v1",
        "event_limit_bytes": event_limit,
        "event_count": event_count,
        "total_event_bytes": total_event_bytes,
        "largest_event_bytes": largest_event_bytes,
        "omitted_event_count": omitted_event_count,
    });
    Ok((events, session, terminal, stream_budget))
}

fn execute_agent_turn(fleet_root: &Path, spec: &AgentTurnSpec, goals: &str) -> Result<Value> {
    execute_agent_turn_with_runtime(fleet_root, spec, goals, None)
}

fn render_agent_turn_prompt(spec: &AgentTurnSpec, goals: &str) -> String {
    if spec.id == "main" {
        format!(
            "{}\n\nApplicable revisioned goals:\n{}\n\nCurrent request:\n{}",
            spec.instructions.trim(),
            goals,
            spec.request.trim()
        )
    } else {
        format!(
            "{}\n\nCurrent assignment:\n{}",
            spec.instructions.trim(),
            spec.request.trim()
        )
    }
}

fn agent_turn_argv(executable: &Path, spec: &AgentTurnSpec, prompt: String) -> Vec<String> {
    let mut argv = vec![
        executable.display().to_string(),
        "--store".into(),
        spec.store.display().to_string(),
        "--color".into(),
        "never".into(),
        "run".into(),
        "--stream-json".into(),
        "--yes".into(),
    ];
    if spec.resume {
        argv.push("--continue".into());
    }
    if let Some(model) = spec.model.as_deref() {
        argv.extend(["--model".into(), model.into()]);
    }
    if spec.enforce_operation_ceiling {
        argv.push("--operation-ceiling".into());
        for operation in &spec.admitted_operations {
            argv.extend(["--operation".into(), operation.clone()]);
        }
    }
    for root in &spec.read_roots {
        argv.extend(["--add-dir".into(), display_path(root)]);
    }
    argv.push(prompt);
    argv
}

fn execute_agent_turn_with_runtime(
    fleet_root: &Path,
    spec: &AgentTurnSpec,
    goals: &str,
    runtime: Option<&tokio::runtime::Handle>,
) -> Result<Value> {
    let store = spec.store.clone();
    let prompt = render_agent_turn_prompt(spec, goals);
    let argv = agent_turn_argv(&std::env::current_exe()?, spec, prompt);
    let environment = if spec.shell_capability {
        vec![("FLUX_ENABLE_BASH".to_string(), "1".to_string())]
    } else {
        Vec::new()
    };
    let output = match runtime {
        Some(runtime) => guarded_agent_run_on(
            runtime,
            &spec.worktree,
            &spec.read_roots,
            fleet_root,
            &spec.id,
            &environment,
            &argv,
        ),
        None => guarded_agent_run(
            &spec.worktree,
            &spec.read_roots,
            fleet_root,
            &spec.id,
            &environment,
            &argv,
        ),
    }
    .with_context(|| format!("transient-worker: agent {} could not start", spec.id))?;
    let (events, session, terminal, stream_budget) =
        parse_fleet_agent_events(&output.stdout, &spec.id, FLEET_AGENT_EVENT_LIMIT).with_context(
            || {
                format!(
                    "transient-worker: agent {} emitted an invalid event stream: {}",
                    spec.id,
                    clipped_redacted(output.stderr.as_bytes())
                )
            },
        )?;
    if output.exit_code != 0 || terminal["outcome"].as_str() != Some("ok") {
        bail!(
            "transient-worker: agent {} turn failed: {}{}",
            spec.id,
            terminal["error"].as_str().unwrap_or("non-zero exit"),
            if output.stderr.trim().is_empty() {
                String::new()
            } else {
                format!("; {}", clipped_redacted(output.stderr.as_bytes()))
            }
        )
    }
    Ok(redact_value(json!({
        "schema": "flux.fleet-agent-turn/v1",
        "agent": spec.id,
        "session": session,
        "ack": "completed",
        "answer": terminal["answer"],
        "usage": terminal["usage"],
        "events": events,
        "stream_budget": stream_budget,
        "context_origin": spec.context_origin.clone(),
        "capability_set": spec.capability_set.clone(),
        "store": display_path(&store),
        "exit_code": output.exit_code,
    })))
}

fn execute_and_record_agent_turn(
    command: &FleetCommand,
    root: &Path,
    state: &mut FleetState,
    spec: AgentTurnSpec,
    intake_id: Option<&str>,
) -> Result<Value> {
    if command.dry_run {
        return Ok(json!({
            "schema": "flux.fleet-agent-turn/v1",
            "agent": spec.id,
            "ack": "accepted",
            "dry_run": true,
            "context_origin": spec.context_origin,
            "capability_set": spec.capability_set,
        }));
    }
    state.revision += 1;
    if spec.id == "main" {
        state.main_agent.status = "working".into();
    } else if let Some(agent) = state.agents.get_mut(&spec.id) {
        agent["status"] = json!("working");
    }
    if let Some(intake_id) = intake_id {
        if let Some(intake) = state.intake.get_mut(intake_id) {
            intake["ack"] = json!("delivered");
        }
    }
    persist_fleet_mutation(
        command,
        root,
        state,
        "agent.turn.delivered",
        json!({"agent": spec.id, "intake": intake_id, "ack": "delivered", "capability_set": spec.capability_set.clone()}),
    )?;

    let goals = scoped_goals(state);
    let outcome = execute_agent_turn(root, &spec, &goals);
    if let Ok(latest) = read_fleet_state(root) {
        if latest.revision > state.revision {
            *state = latest;
        }
    }
    let cancelled = if spec.id == "main" {
        state.main_agent.status == "cancelled"
    } else {
        state.agents[&spec.id]["status"].as_str() == Some("cancelled")
    };
    let outcome = if cancelled && outcome.is_ok() {
        Err(anyhow::anyhow!(
            "transient-worker: agent {} completed after cancellation was requested; result was not accepted",
            spec.id
        ))
    } else {
        outcome
    };
    match outcome {
        Ok(receipt) => {
            state.revision += 1;
            let session = receipt["session"].as_str().map(str::to_string);
            if spec.id == "main" {
                state.main_agent.status = if state.running {
                    "running".into()
                } else {
                    "stopped".into()
                };
                state.main_agent.session = session;
                state.main_agent.last_turn = Some(receipt.clone());
                state.main_agent.last_error = None;
            } else if let Some(agent) = state.agents.get_mut(&spec.id) {
                agent["status"] = json!("completed");
                agent["runtime_session"] = json!(session.clone());
                agent["session"] = json!(session);
                agent["last_turn"] = receipt.clone();
                agent["last_error"] = Value::Null;
            }
            if let Some(intake_id) = intake_id {
                if let Some(intake) = state.intake.get_mut(intake_id) {
                    intake["ack"] = json!("completed");
                    intake["receipt"] = receipt.clone();
                }
            }
            persist_fleet_mutation(
                command,
                root,
                state,
                "agent.turn.completed",
                receipt.clone(),
            )?;
            Ok(receipt)
        }
        Err(error) => {
            state.revision += 1;
            let message = redact(&error.to_string());
            if spec.id == "main" {
                state.main_agent.status = if cancelled {
                    "cancelled".into()
                } else {
                    "failed".into()
                };
                state.main_agent.last_error = Some(message.clone());
            } else if let Some(agent) = state.agents.get_mut(&spec.id) {
                agent["status"] = json!(if cancelled { "cancelled" } else { "failed" });
                agent["last_error"] = json!(message);
            }
            if let Some(intake_id) = intake_id {
                if let Some(intake) = state.intake.get_mut(intake_id) {
                    intake["ack"] = json!("failed");
                    intake["error"] = json!(message);
                }
            }
            persist_fleet_mutation(
                command,
                root,
                state,
                if cancelled {
                    "agent.turn.cancelled"
                } else {
                    "agent.turn.failed"
                },
                json!({"agent": spec.id, "intake": intake_id, "error": message, "cancelled": cancelled}),
            )?;
            Err(error)
        }
    }
}

fn fleet_spawn(
    command: &FleetCommand,
    root: &Path,
    mut state: FleetState,
    options: SpawnOptions<'_>,
) -> Result<(String, Value, Vec<String>, u64)> {
    if !state.running {
        bail!("conflict/precondition: main coordinator is stopped; run `flux fleet start`")
    }
    let config = read_fleet_config(root)?;
    let template = options
        .template
        .map(|id| {
            config
                .agent_templates
                .iter()
                .find(|template| template.id == id)
                .with_context(|| format!("not-found: agent template {id}"))
        })
        .transpose()?;
    if template.is_none() && !config.allow_ad_hoc_agents {
        bail!("permission: ad-hoc agents are disabled by .flux/fleet.toml")
    }
    let role = options
        .role
        .or_else(|| template.map(|template| template.role.as_str()))
        .context("input/schema: ad-hoc spawn requires --role")?;
    if role.trim().is_empty() || role == "coordinator" || role == "main" {
        bail!("input/schema: worker role cannot be empty or coordinator-shaped")
    }
    let mode = options
        .mode
        .or_else(|| template.map(|template| template.mode))
        .unwrap_or_default();
    if mode == FleetTaskMode::Write && options.item.is_none() {
        bail!("input/schema: a write-capable worker requires --item BOARD/ITEM")
    }
    if let Some(item) = options.item {
        validate_board_refs(&[item.to_string()])?;
    }
    let instructions_path = match options.instructions_file {
        Some(path) => Some(confined_config_file(
            root,
            path,
            "ad-hoc agent instructions",
        )?),
        None => template
            .map(|template| {
                confined_config_file(
                    root,
                    &template.instructions,
                    &format!("agent template {} instructions", template.id),
                )
            })
            .transpose()?,
    };
    let instructions = match (options.instructions, instructions_path.as_ref()) {
        (Some(instructions), _) => instructions.to_string(),
        (None, Some(path)) => fs::read_to_string(path)?,
        (None, None) => {
            bail!("input/schema: ad-hoc spawn requires --instructions or --instructions-file")
        }
    };
    if instructions.trim().is_empty() {
        bail!("input/schema: agent instructions cannot be empty")
    }
    if let Some(template) = template {
        let instances = state
            .agents
            .values()
            .filter(|agent| agent["template"].as_str() == Some(&template.id))
            .filter(|agent| {
                !matches!(
                    agent["status"].as_str(),
                    Some("completed" | "cancelled" | "failed")
                )
            })
            .count();
        if instances >= template.max_instances {
            bail!(
                "conflict/precondition: agent template {} already has its {} active instance(s)",
                template.id,
                template.max_instances
            )
        }
    }
    let id = options
        .name
        .map(str::to_string)
        .unwrap_or_else(|| format!("agent-{}", state.revision + 1));
    flux_datasource::board::BoardId::new(&id)
        .map_err(|error| anyhow::anyhow!("input/schema: agent {error}"))?;
    if id == "main" || state.agents.contains_key(&id) {
        bail!("conflict/precondition: agent id {id:?} is reserved or already registered")
    }
    let mut capabilities = match template {
        Some(template) => template.capabilities.clone(),
        None if options.capabilities.is_empty() => match mode {
            FleetTaskMode::ReadOnly => vec!["read".into()],
            FleetTaskMode::Write => DEFAULT_STORY_CAPABILITIES
                .iter()
                .map(|capability| (*capability).to_string())
                .collect(),
        },
        None => Vec::new(),
    };
    capabilities.extend(options.capabilities.iter().cloned());
    let (capabilities, operations) = normalize_worker_capabilities(mode, &capabilities)?;
    let mut fences = template
        .map(|template| template.fences.clone())
        .unwrap_or_default();
    fences.extend(options.fences.iter().cloned());
    let fences = normalize_fences(fences);
    let read_roots = config
        .repositories
        .iter()
        .map(|repository| repository_root(root, repository))
        .collect::<Result<Vec<_>>>()?;
    let capability_set =
        capability_set_manifest(mode, &capabilities, &operations, root, &read_roots, &fences);
    state.revision += 1;
    let registration = json!({
        "schema": "flux.fleet-agent-registration/v1",
        "id": id,
        "parent": "main",
        "role": role,
        "template": template.map(|template| template.id.as_str()),
        "ephemeral": template.is_none(),
        "transport": "flux-local",
        "model": options.model.or_else(|| template.and_then(|template| template.model.as_deref())),
        "mode": mode,
        "board_ref": options.item,
        "instructions": redact(&instructions),
        "instructions_source": instructions_path.as_ref().map(|path| display_path(path)),
        "capabilities": capabilities,
        "fences": fences,
        "writable_root": display_path(root),
        "read_roots": read_roots.iter().map(|root| display_path(root)).collect::<Vec<_>>(),
        "capability_set": capability_set,
        "status": "admitted",
        "lease": {"generation": state.revision, "holder": id, "status": "active"},
        "created_by": "main",
    });
    state.agents.insert(id.clone(), registration.clone());
    persist_fleet_mutation(
        command,
        root,
        &state,
        "agent.admitted",
        registration.clone(),
    )?;
    Ok((
        format!("{id} admitted by main coordinator"),
        registration,
        vec![],
        state.revision,
    ))
}

fn fleet_goal(
    command: &FleetCommand,
    root: &Path,
    mut state: FleetState,
    action: &FleetGoalAction,
) -> Result<(String, Value, Vec<String>, u64)> {
    match action {
        FleetGoalAction::List => {
            let goals = state.goals.values().cloned().collect::<Vec<_>>();
            let human = goals
                .iter()
                .map(|goal| format!("{}/{}\t{}", goal.scope.as_str(), goal.name, goal.statement))
                .collect::<Vec<_>>()
                .join("\n");
            Ok((
                human,
                json!({"goals": goals, "goals_revision": state.main_agent.goals_revision}),
                vec![],
                state.revision,
            ))
        }
        FleetGoalAction::Show { scope, name } => {
            let key = goal_key(*scope, name)?;
            let goal = state
                .goals
                .get(&key)
                .cloned()
                .with_context(|| format!("not-found: fleet goal {key}"))?;
            Ok((
                goal.statement.clone(),
                serde_json::to_value(goal)?,
                vec![],
                state.revision,
            ))
        }
        FleetGoalAction::Set {
            scope,
            name,
            statement,
        } => {
            if statement.trim().is_empty() {
                bail!("input/schema: goal statement cannot be empty")
            }
            let key = goal_key(*scope, name)?;
            state.revision += 1;
            state.main_agent.goals_revision += 1;
            let goal = FleetGoal {
                scope: *scope,
                name: name.clone(),
                statement: redact(statement),
                revision: state.main_agent.goals_revision,
            };
            state.goals.insert(key.clone(), goal.clone());
            let data = json!({"key": key, "goal": goal, "main_agent": "main"});
            persist_fleet_mutation(command, root, &state, "coordinator.goal.set", data.clone())?;
            Ok((
                format!("goal {key} set for main coordinator"),
                data,
                vec![],
                state.revision,
            ))
        }
        FleetGoalAction::Remove { scope, name } => {
            let key = goal_key(*scope, name)?;
            if !state.goals.contains_key(&key) {
                bail!("not-found: fleet goal {key}")
            }
            state.revision += 1;
            state.main_agent.goals_revision += 1;
            state.goals.remove(&key);
            let data = json!({"key": key, "removed": true, "main_agent": "main"});
            persist_fleet_mutation(
                command,
                root,
                &state,
                "coordinator.goal.removed",
                data.clone(),
            )?;
            Ok((format!("goal {key} removed"), data, vec![], state.revision))
        }
    }
}

fn goal_key(scope: GoalScope, name: &str) -> Result<String> {
    flux_datasource::board::BoardId::new(name)
        .map_err(|error| anyhow::anyhow!("input/schema: goal name {error}"))?;
    Ok(format!("{}/{}", scope.as_str(), name))
}

fn fleet_control_mutation(
    command: &FleetCommand,
    root: &Path,
    mut state: FleetState,
    verb: &str,
    target: &str,
) -> Result<(String, Value, Vec<String>, u64)> {
    match verb {
        "cancelled" if target == "main" => state.main_agent.status = "cancelled".into(),
        "cancelled" if state.agents.contains_key(target) => {
            state.agents.get_mut(target).unwrap()["status"] = json!("cancelled");
        }
        "cancelled" if state.waves.contains_key(target) => {
            state.waves.get_mut(target).unwrap()["status"] = json!("cancelled");
            for agent in state.agents.values_mut().filter(|agent| {
                agent["id"]
                    .as_str()
                    .is_some_and(|id| id.starts_with(&format!("{target}-worker-")))
            }) {
                agent["status"] = json!("cancelled");
            }
        }
        "cancelled" => bail!("not-found: fleet agent or wave {target}"),
        _ => {}
    }
    state.revision += 1;
    let data = json!({"target":target,"state":verb,"ack":"completed"});
    persist_fleet_mutation(
        command,
        root,
        &state,
        &format!("worker.{verb}"),
        data.clone(),
    )?;
    Ok((format!("{target} {verb}"), data, vec![], state.revision))
}
fn read_event_lines(root: &Path, limit: usize) -> Result<Vec<Value>> {
    let content = guarded_system(root)?
        .read_optional_text(".flux/fleet/events.ndjson")?
        .unwrap_or_default();
    let mut lines = content
        .lines()
        .rev()
        .take(limit.min(10_000))
        .filter_map(|line| serde_json::from_str(line).ok())
        .collect::<Vec<_>>();
    lines.reverse();
    Ok(lines)
}

fn fleet_inspect(
    root: &Path,
    state: &FleetState,
    view: InspectView,
    target: Option<&str>,
    limit: usize,
) -> Result<Value> {
    let limit = limit.min(10_000);
    let target_required = || target.context("input/schema: this inspect view requires a target");
    let payload = match view {
        InspectView::Snapshot => json!({
            "revision":state.revision,
            "running":state.running,
            "main_agent":state.main_agent,
            "goals_revision":state.main_agent.goals_revision,
            "goals":state.goals.len(),
            "intake":state.intake.len(),
            "workers":state.agents.len(),
            "waves":state.waves.len(),
        }),
        InspectView::Wave => {
            if let Some(target) = target {
                state
                    .waves
                    .get(target)
                    .cloned()
                    .with_context(|| format!("not-found: wave {target}"))?
            } else {
                json!({"waves":state.waves.iter().rev().take(limit).map(|(id,wave)|json!({"id":id,"status":wave["status"],"items":wave["items"],"apply_eligible":wave["apply_eligible"]})).collect::<Vec<_>>()})
            }
        }
        InspectView::Worker => {
            let target = target_required()?;
            if target == "main" {
                serde_json::to_value(&state.main_agent)?
            } else {
                state
                    .agents
                    .get(target)
                    .cloned()
                    .with_context(|| format!("not-found: worker {target}"))?
            }
        }
        InspectView::Result => {
            let target = target_required()?;
            let mut results = Vec::new();
            for (wave_id, wave) in state.waves.iter().rev() {
                for repository in wave["topology"]["repositories"]
                    .as_array()
                    .into_iter()
                    .flatten()
                {
                    for story in repository["stories"].as_array().into_iter().flatten() {
                        if story["board_ref"].as_str() == Some(target) {
                            results.push(json!({"wave":wave_id,"status":story["status"],"handoff":story["handoff"],"reviews":story["reviews"]}));
                        }
                    }
                }
            }
            json!({"board_ref":target,"results":results.into_iter().take(limit).collect::<Vec<_>>()})
        }
        InspectView::Activity => json!({"events":read_event_lines(root,limit)?}),
        InspectView::Worktree => {
            let mut data = fleet_worktrees(root)?;
            if let Some(target) = target {
                if let Some(worktrees) = data["worktrees"].as_array_mut() {
                    worktrees.retain(|worktree| worktree.to_string().contains(target));
                    worktrees.truncate(limit);
                }
            } else if let Some(worktrees) = data["worktrees"].as_array_mut() {
                worktrees.truncate(limit);
            }
            data
        }
        InspectView::Integration => {
            let target = target_required()?;
            let wave = state
                .waves
                .get(target)
                .with_context(|| format!("not-found: wave {target}"))?;
            json!({"wave":target,"status":wave["status"],"apply_eligible":wave["apply_eligible"],"integration_order":wave["integration_order"],"repositories":wave["topology"]["repositories"].as_array().into_iter().flatten().map(|repository|json!({"id":repository["id"],"base_commit":repository["base_commit"],"integration":repository["integration"],"candidate":repository["candidate"],"gate":repository["gate"]})).take(limit).collect::<Vec<_>>()})
        }
        InspectView::Source => {
            let mut sources = fleet_sources(root)?;
            if let Some(target) = target {
                if let Some(repositories) = sources["repositories"].as_array_mut() {
                    repositories.retain(|repository| repository["id"].as_str() == Some(target));
                    if repositories.is_empty() {
                        bail!("not-found: fleet source {target}")
                    }
                }
            }
            sources
        }
        InspectView::Search => {
            let target = target_required()?;
            let needle = target.to_ascii_lowercase();
            let matches = read_event_lines(root, 10_000)?
                .into_iter()
                .rev()
                .filter(|event| event.to_string().to_ascii_lowercase().contains(&needle))
                .take(limit)
                .collect::<Vec<_>>();
            json!({"query":target,"events":matches})
        }
        InspectView::Story => {
            let target = target_required()?;
            let stories =
                if read_fleet_config(root).is_ok_and(|config| !config.repositories.is_empty()) {
                    workspace_stories(root)?
                } else {
                    read_stories(root)?
                        .into_iter()
                        .map(|mut story| {
                            story.id = format!("default/{}", story.id);
                            story
                        })
                        .collect()
                };
            let story = stories
                .into_iter()
                .find(|story| story.id == target)
                .with_context(|| format!("not-found: story {target}"))?;
            let execution = fleet_inspect(root, state, InspectView::Result, Some(target), limit)?;
            json!({"planning":story,"execution":execution})
        }
        InspectView::PullRequest => {
            let target = target_required()?;
            let wave = state
                .waves
                .get(target)
                .with_context(|| format!("not-found: wave {target}"))?;
            json!({"wave":target,"supported":false,"reason":"fleet never opens pull requests; inspect the local candidate and apply explicitly","status":wave["status"],"apply_eligible":wave["apply_eligible"]})
        }
    };
    Ok(redact_value(json!({
        "schema":"flux.fleet-inspect/v1",
        "view":format!("{view:?}").to_ascii_lowercase(),
        "target":target,
        "bounded":true,
        "limit":limit,
        "data":payload,
    })))
}

fn fleet_sources(root: &Path) -> Result<Value> {
    let path = root.join(".flux/fleet.toml");
    if !path.is_file() {
        return Ok(
            json!({"root": display_path(root), "config": false, "repositories": [], "modified": false}),
        );
    }
    let config = read_fleet_config(root)?;
    let mut repositories = Vec::new();
    for repository in &config.repositories {
        let repo_root = repository_root(root, repository)?;
        let head = git_output(&repo_root, &["rev-parse", "HEAD"]);
        let canonical = git_output(&repo_root, &["rev-parse", &repository.canonical_ref]);
        let status = git_output(&repo_root, &["status", "--porcelain"]);
        repositories.push(json!({
            "id": repository.id, "root": display_path(&repo_root), "board": repository.board,
            "canonical_ref": repository.canonical_ref, "head": head, "canonical_commit": canonical,
            "dirty": status.is_some_and(|value| !value.is_empty()),
            "stale_or_diverged": head.is_some() && canonical.is_some() && head != canonical,
            "gate": repository.gate, "fences": repository.fences,
            "concurrency": repository.concurrency, "modified": false
        }));
    }
    Ok(json!({
        "root": display_path(root),
        "config": true,
        "main": {"instructions": config.main.instructions, "model": config.main.model},
        "allow_ad_hoc_agents": config.allow_ad_hoc_agents,
        "worktree_root": config.worktree_root,
        "agent_templates": config.agent_templates.iter().map(|template| json!({
            "id": template.id, "role": template.role, "mode": template.mode,
            "model": template.model, "max_instances": template.max_instances,
            "capabilities": template.capabilities, "fences": template.fences
        })).collect::<Vec<_>>(),
        "repositories": repositories,
        "modified": false
    }))
}

fn open_decisions(root: &Path) -> Result<Value> {
    fn collect(root: &Path, namespace: &str, out: &mut Vec<Value>) -> Result<()> {
        let dir = if root.join("decisions").is_dir() {
            root.join("decisions")
        } else {
            root.join("docs/decisions")
        };
        for mut decision in decision_records(&dir)? {
            if decision["status"].as_str() != Some("open") {
                continue;
            }
            let id = decision["id"].as_str().unwrap_or_default();
            decision["ref"] = json!(format!("{namespace}/{id}"));
            decision["board"] = json!(namespace);
            decision["attention_required"] = json!(true);
            out.push(decision);
        }
        Ok(())
    }

    let mut decisions = Vec::new();
    collect(root, "workspace", &mut decisions)?;
    let config_path = root.join(".flux/fleet.toml");
    if config_path.is_file() {
        let config = read_fleet_config(root)?;
        for repository in &config.repositories {
            collect(
                &repository_root(root, repository)?,
                &repository.id,
                &mut decisions,
            )?;
        }
    }
    decisions.sort_by(|a, b| {
        a["ref"]
            .as_str()
            .unwrap_or_default()
            .cmp(b["ref"].as_str().unwrap_or_default())
    });
    Ok(json!(decisions))
}

fn fleet_schedule(root: &Path) -> Result<Value> {
    let config = read_fleet_config(root).ok();
    let stories = if config
        .as_ref()
        .is_some_and(|value| !value.repositories.is_empty())
    {
        workspace_stories(root)?
    } else {
        read_stories(root).unwrap_or_default()
    };
    let states = stories
        .iter()
        .map(|story| (story.id.clone(), story.status.clone()))
        .collect::<BTreeMap<_, _>>();
    let mut ready = stories
        .into_iter()
        .filter(|story| {
            story.status == "ready"
                && story.dependencies.iter().all(|dependency| {
                    states
                        .get(dependency)
                        .is_some_and(|status| status == "done")
                })
        })
        .collect::<Vec<_>>();
    sort_ready(&mut ready);
    let max_wave = config.as_ref().map_or(10, |value| value.max_wave);
    let ready_refs = ready
        .into_iter()
        .take(max_wave)
        .map(|story| {
            if story.id.contains('/') {
                story.id
            } else {
                format!("default/{}", story.id)
            }
        })
        .collect::<Vec<_>>();
    let waves = if let Some(config) = &config {
        if config.waves.is_empty() {
            vec![json!({"id": "ready", "items": ready_refs})]
        } else {
            let ready_set = ready_refs.iter().collect::<BTreeSet<_>>();
            config
                .waves
                .iter()
                .map(|wave| {
                    let eligible = wave
                        .items
                        .iter()
                        .filter(|item| ready_set.contains(item))
                        .cloned()
                        .collect::<Vec<_>>();
                    json!({"id": wave.id, "items": wave.items, "eligible": eligible, "depends_on": wave.depends_on})
                })
                .collect()
        }
    } else {
        vec![json!({"id": "ready", "items": ready_refs})]
    };
    let active_tranche = config.as_ref().and_then(|config| {
        config
            .tranches
            .iter()
            .find(|tranche| tranche.active)
            .map(|tranche| tranche.id.clone())
    });
    let human_decisions = open_decisions(root)?;
    Ok(json!({
        "schema": "flux.fleet-schedule/v1", "active_tranche": active_tranche,
        "waves": waves, "tranches": config.as_ref().map(|value| &value.tranches),
        "groups": config.as_ref().map(|value| &value.groups), "max_wave": max_wave,
        "human_decisions": human_decisions,
        "attention_required": !human_decisions.as_array().is_none_or(Vec::is_empty)
    }))
}
