fn list_items(
    command: &BoardCommand,
    root: &Path,
    status: Option<&str>,
    area: Option<&str>,
    text: Option<&str>,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let mut stories = read_board_items(command, root)?;
    stories.retain(|story| {
        status.is_none_or(|v| story.status == normalize_status(v))
            && area.is_none_or(|v| story.areas.iter().any(|a| a == v))
            && text.is_none_or(|v| {
                story
                    .body
                    .to_ascii_lowercase()
                    .contains(&v.to_ascii_lowercase())
            })
    });
    item_result(stories)
}

