fn guarded_system(root: &Path) -> Result<flux_system::System> {
    flux_system::System::from_env(root).map_err(|error| anyhow::anyhow!(error.to_string()))
}

/// Run trusted control-plane argv through Flux's one guarded process boundary.
///
/// Board/fleet commands are synchronous projections inside the CLI's multi-thread Tokio runtime.
/// `block_in_place` lets them use the async System port without constructing a second runtime or a
/// raw `Command`. The one-hour ceiling is deliberately finite: a wedged gate remains inspectable
/// and cancellable instead of pinning the coordinator forever.
fn guarded_run(root: &Path, argv: &[String]) -> Result<flux_system::ProcessOutput> {
    if argv.is_empty() {
        bail!("input/schema: process argv cannot be empty")
    }
    let system = guarded_system(root)?;
    tokio::task::block_in_place(|| {
        tokio::runtime::Handle::current()
            .block_on(system.run(argv, CONTROL_PROCESS_TIMEOUT))
            .map_err(|error| anyhow::anyhow!(error.to_string()))
    })
}

/// Retain only complete newest lines within `limit` bytes.
///
/// Agent stream events are one JSON object per line. Cutting bytes from the front of an oversized
/// in-flight line creates invalid JSON and can hide a later terminal event. Once a line itself
/// exceeds the window, discard that whole line through its newline, then resume capture at the next
/// event. This keeps memory bounded and every retained line parseable.
fn append_capped_line_buffer(
    buffer: &mut Vec<u8>,
    dropping_line: &mut bool,
    bytes: &[u8],
    limit: usize,
) {
    if limit == 0 {
        buffer.clear();
        *dropping_line = !bytes.ends_with(b"\n");
        return;
    }
    let mut remaining = bytes;
    if *dropping_line {
        let Some(newline) = remaining.iter().position(|byte| *byte == b'\n') else {
            return;
        };
        remaining = &remaining[newline + 1..];
        *dropping_line = false;
    }
    buffer.extend_from_slice(remaining);
    while buffer.len() > limit {
        if let Some(newline) = buffer.iter().position(|byte| *byte == b'\n') {
            buffer.drain(..=newline);
        } else {
            buffer.clear();
            *dropping_line = true;
            break;
        }
    }
}

fn guarded_git(root: &Path, args: &[&str]) -> Result<flux_system::ProcessOutput> {
    let argv = std::iter::once("git".to_string())
        .chain(args.iter().map(|argument| (*argument).to_string()))
        .collect::<Vec<_>>();
    guarded_run(root, &argv)
}

async fn guarded_agent_run_async(
    worktree: &Path,
    read_roots: &[PathBuf],
    fleet_root: &Path,
    agent_id: &str,
    environment: &[(String, String)],
    argv: &[String],
) -> Result<flux_system::ProcessOutput> {
    const CAPTURE_LIMIT: usize = 1024 * 1024;
    let mut workspace = flux_system::Workspace::from_env(worktree)
        .map_err(|error| anyhow::anyhow!(error.to_string()))?;
    for root in read_roots {
        workspace
            .add_read_root(root)
            .map_err(|error| anyhow::anyhow!(error.to_string()))?;
    }
    let system = flux_system::System::new(workspace).with_sandbox(
        flux_system::sandbox::Sandbox::resolve(flux_system::sandbox::SandboxSettings::from_env()),
    );
    let argv = argv.to_vec();
    let fleet_root = fleet_root.to_path_buf();
    let agent_id = agent_id.to_string();
    let mut environment = environment.to_vec();
    environment.push((
        crate::stream_json::STREAM_JSON_LINE_LIMIT_ENV.to_string(),
        FLEET_STREAM_JSON_LINE_LIMIT.to_string(),
    ));
    let mut child = system
        .spawn_background(&argv, &environment)
        .map_err(|error| anyhow::anyhow!(error.to_string()))?;
    let deadline = tokio::time::Instant::now() + CONTROL_PROCESS_TIMEOUT;
    let mut stdout = Vec::new();
    let mut stderr = Vec::new();
    let mut dropping_stdout_line = false;
    let mut dropping_stderr_line = false;
    loop {
        let (out, err) = child.read_output();
        append_capped_line_buffer(
            &mut stdout,
            &mut dropping_stdout_line,
            out.as_bytes(),
            CAPTURE_LIMIT,
        );
        append_capped_line_buffer(
            &mut stderr,
            &mut dropping_stderr_line,
            err.as_bytes(),
            CAPTURE_LIMIT,
        );
        let status = child.status();
        if !status.running {
            // The child can exit a few scheduler ticks before the async pipe drains publish their
            // final bytes. Collect that bounded tail so `turn_end` is never lost at process exit.
            for _ in 0..5 {
                tokio::time::sleep(Duration::from_millis(10)).await;
                let (out, err) = child.read_output();
                append_capped_line_buffer(
                    &mut stdout,
                    &mut dropping_stdout_line,
                    out.as_bytes(),
                    CAPTURE_LIMIT,
                );
                append_capped_line_buffer(
                    &mut stderr,
                    &mut dropping_stderr_line,
                    err.as_bytes(),
                    CAPTURE_LIMIT,
                );
            }
            return Ok(flux_system::ProcessOutput {
                stdout: String::from_utf8_lossy(&stdout).into_owned(),
                stderr: String::from_utf8_lossy(&stderr).into_owned(),
                exit_code: status.exit_code.unwrap_or(-1),
            });
        }
        let cancelled = read_fleet_state(&fleet_root).ok().is_some_and(|state| {
            if agent_id == "main" {
                state.main_agent.status == "cancelled"
            } else {
                state.agents[&agent_id]["status"].as_str() == Some("cancelled")
            }
        });
        if cancelled {
            child.kill();
            bail!("transient-worker: agent {agent_id} was cancelled by the durable fleet state")
        }
        if tokio::time::Instant::now() >= deadline {
            child.kill();
            bail!("transient-worker: agent {agent_id} exceeded the one-hour turn deadline")
        }
        tokio::time::sleep(Duration::from_millis(50)).await;
    }
}

fn guarded_agent_run(
    worktree: &Path,
    read_roots: &[PathBuf],
    fleet_root: &Path,
    agent_id: &str,
    environment: &[(String, String)],
    argv: &[String],
) -> Result<flux_system::ProcessOutput> {
    tokio::task::block_in_place(|| {
        tokio::runtime::Handle::current().block_on(guarded_agent_run_async(
            worktree,
            read_roots,
            fleet_root,
            agent_id,
            environment,
            argv,
        ))
    })
}

fn guarded_agent_run_on(
    runtime: &tokio::runtime::Handle,
    worktree: &Path,
    read_roots: &[PathBuf],
    fleet_root: &Path,
    agent_id: &str,
    environment: &[(String, String)],
    argv: &[String],
) -> Result<flux_system::ProcessOutput> {
    runtime.block_on(guarded_agent_run_async(
        worktree,
        read_roots,
        fleet_root,
        agent_id,
        environment,
        argv,
    ))
}

