fn export_documents(root: &Path) -> Result<Value> {
    let read = |path: &Path| -> BTreeMap<String, String> {
        let mut result = BTreeMap::new();
        if let Ok(entries) = fs::read_dir(path) {
            for entry in entries.filter_map(Result::ok) {
                if entry.path().extension().and_then(|value| value.to_str()) != Some("md") {
                    continue;
                }
                if let Ok(body) = fs::read_to_string(entry.path()) {
                    result.insert(entry.file_name().to_string_lossy().into_owned(), body);
                }
            }
        }
        result
    };
    Ok(
        json!({"vision":fs::read_to_string(root.join("docs/VISION.md")).ok(),"roadmap":fs::read_to_string(root.join("docs/ROADMAP.md")).ok(),"decisions":read(&root.join("docs/decisions")),"designs":read(&root.join("docs/designs"))}),
    )
}

