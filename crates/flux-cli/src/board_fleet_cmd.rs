pub(super) fn run_board(command: BoardCommand) -> Result<()> {
    let output = command.output;
    match run_board_checked(command) {
        Ok(()) => Ok(()),
        Err(error) => emit_error(output, error),
    }
}

fn run_board_checked(command: BoardCommand) -> Result<()> {
    let request = load_request(command.request.as_deref())?;
    let envelope_request_id = request_id_from(request.as_ref())?;
    if command.scope == BoardScopeArg::Session {
        validate_board_common(&command, request.as_ref())?;
        return run_session_board_checked(&command, request);
    }
    let workspace_root = confined_root(&command.root)?;
    validate_board_common(&command, request.as_ref())?;
    if command.scope == BoardScopeArg::Workspace
        && board_action_requires_member(&command.action)
        && command.board.is_none()
    {
        bail!("input/schema: a workspace mutation must select its authoritative member with --board MEMBER")
    }
    let root = if command.scope == BoardScopeArg::Workspace {
        match command.board.as_deref() {
            Some(member) => member_root(&workspace_root, member)?,
            None => workspace_root.clone(),
        }
    } else {
        workspace_root.clone()
    };
    let revision = scoped_board_revision(&command, &workspace_root)?;
    let fingerprint = request_fingerprint(&command.action, request.as_ref());
    if let Some(stored) = board_idempotency_hit(&command, &workspace_root, &fingerprint)? {
        return emit(
            command.output,
            &stored.human,
            stored.data,
            stored.warnings,
            Some(&stored.revision),
            envelope_request_id.as_deref(),
        );
    }
    check_revision(command.if_revision.as_deref(), &revision)?;
    let result = run_board_action(&command, &root, request, &revision);
    match result {
        Ok((human, data, warnings, next_revision)) => {
            let next_revision = if next_revision.is_some() && !command.dry_run {
                scoped_board_revision(&command, &workspace_root)?
            } else {
                next_revision.unwrap_or(revision)
            };
            store_board_idempotency(
                &command,
                &workspace_root,
                StoredResult {
                    fingerprint,
                    human: human.clone(),
                    data: data.clone(),
                    warnings: warnings.clone(),
                    revision: next_revision.clone(),
                },
            )?;
            emit(
                command.output,
                &human,
                data,
                warnings,
                Some(&next_revision),
                envelope_request_id.as_deref(),
            )
        }
        Err(error) => Err(error),
    }
}

fn run_session_board_checked(command: &BoardCommand, request: Option<Value>) -> Result<()> {
    use flux_datasource::board::{BoardBackend, BoardContract, BoardId, BoardProfile, BoardScope};

    let envelope_request_id = request_id_from(request.as_ref())?;
    let events = std::sync::Arc::new(open_event_store()?);
    let requested = command
        .session
        .clone()
        .or_else(|| std::env::var("FLUX_SESSION_ID").ok())
        .context("input/schema: session boards require --session ID|last outside a live turn")?;
    let session = if requested == "last" {
        events
            .latest_session()?
            .context("not-found: no recorded session for --session last")?
    } else {
        events
            .info(&requested)
            .with_context(|| format!("not-found: session {requested}"))?;
        requested
    };
    let board_id = BoardId::new(command.board.as_deref().unwrap_or("default"))
        .map_err(|error| anyhow::anyhow!("input/schema: {error}"))?;
    let profile = match command.profile {
        BoardProfileArg::General => BoardProfile::General,
        BoardProfileArg::Planning => BoardProfile::Planning,
        BoardProfileArg::Execution => BoardProfile::Execution,
    };
    let contract = BoardContract {
        id: board_id.clone(),
        scope: BoardScope::Session {
            session_id: session.clone(),
        },
        profile,
        backend: BoardBackend::Session,
        source: "flux board CLI".into(),
    };
    let board = flux_capabilities::SessionBoard::open(events.clone(), &session, contract)
        .map_err(session_board_error)?;
    let snapshot = board.snapshot().map_err(session_board_error)?;
    let fingerprint = request_fingerprint(&command.action, request.as_ref());
    let mut idempotent_retry = false;
    let request_id = if let Some(key) = command.idempotency_key.as_deref() {
        let request_id = format!("{key}:{fingerprint}");
        let prefix = format!("session-board:{session}:{board_id}:{key}:");
        let expected_id = format!("session-board:{session}:{board_id}:{request_id}");
        for event in events.load_stream(&session, None)? {
            if event.id == expected_id {
                idempotent_retry = true;
            } else if event.id.starts_with(&prefix) {
                bail!("conflict/precondition: idempotency key was already used for a different session-board request")
            }
        }
        Some(request_id)
    } else {
        None
    };
    if !idempotent_retry {
        check_revision(
            command.if_revision.as_deref(),
            &snapshot.revision.to_string(),
        )?;
    }
    let (human, data, warnings, revision) =
        run_session_board_action(command, &board, snapshot, request_id.as_deref(), request)?;
    emit(
        command.output,
        &human,
        data,
        warnings,
        Some(&revision.to_string()),
        envelope_request_id.as_deref(),
    )
}

fn session_board_error(error: flux_core::Error) -> anyhow::Error {
    let message = error.to_string();
    if message.contains("stale") {
        anyhow::anyhow!("conflict/precondition: {message}")
    } else if message.contains("unknown board item") {
        anyhow::anyhow!("not-found: {message}")
    } else {
        anyhow::anyhow!("validation/gate: {message}")
    }
}

fn session_snapshot_value(snapshot: &flux_capabilities::SessionBoardSnapshot) -> Value {
    let items = snapshot
        .items
        .values()
        .map(|item| {
            let mut value = serde_json::to_value(item).unwrap_or(Value::Null);
            if let Some(object) = value.as_object_mut() {
                object.insert("status".into(), json!(item.state));
            }
            value
        })
        .collect::<Vec<_>>();
    json!({
        "schema": snapshot.schema,
        "board": snapshot.board,
        "profile": snapshot.profile,
        "revision": snapshot.revision,
        "items": items,
    })
}

fn run_session_board_action(
    command: &BoardCommand,
    board: &flux_capabilities::SessionBoard,
    snapshot: flux_capabilities::SessionBoardSnapshot,
    request_id: Option<&str>,
    _request: Option<Value>,
) -> Result<(String, Value, Vec<String>, u64)> {
    use flux_datasource::board::ItemId;
    let current = snapshot.revision;
    let read_item = |id: &str| -> Result<Value> {
        let id = ItemId::new(id).map_err(|error| anyhow::anyhow!("input/schema: {error}"))?;
        let item = snapshot
            .items
            .get(&id)
            .with_context(|| format!("not-found: item {id}"))?;
        let mut value = serde_json::to_value(item)?;
        value["status"] = json!(item.state);
        Ok(value)
    };
    match &command.action {
        BoardAction::Skill => {
            let skill = board_skill();
            Ok((
                skill.clone(),
                skill_json("flux-board", &skill, "board"),
                vec![],
                current,
            ))
        }
        BoardAction::Schema => Ok((
            "Use `--output json` for the flux.cli/v1 board schema.".into(),
            family_schema("board", board_operations()),
            vec![],
            current,
        )),
        BoardAction::Init { .. } | BoardAction::Show | BoardAction::List => Ok((
            format!(
                "session board {}: {} item(s), revision {current}",
                snapshot.board,
                snapshot.items.len()
            ),
            session_snapshot_value(&snapshot),
            vec![],
            current,
        )),
        BoardAction::Items => Ok((
            snapshot
                .items
                .values()
                .map(|item| format!("{}\t{}\t{}", item.id, item.state, item.title))
                .collect::<Vec<_>>()
                .join("\n"),
            session_snapshot_value(&snapshot),
            vec![],
            current,
        )),
        BoardAction::Get { id } => {
            let value = read_item(id)?;
            Ok((serde_json::to_string_pretty(&value)?, value, vec![], current))
        }
        BoardAction::Query { status, text, .. } => {
            let mut items = snapshot
                .items
                .values()
                .filter(|item| {
                    status
                        .as_deref()
                        .is_none_or(|status| normalize_status(status) == item.state)
                        && text.as_deref().is_none_or(|text| {
                            let text = text.to_ascii_lowercase();
                            item.title.to_ascii_lowercase().contains(&text)
                                || item.description.to_ascii_lowercase().contains(&text)
                        })
                })
                .cloned()
                .collect::<Vec<_>>();
            items.sort_by(|a, b| natural_cmp(a.id.as_str(), b.id.as_str()));
            Ok((
                items
                    .iter()
                    .map(|item| format!("{}\t{}\t{}", item.id, item.state, item.title))
                    .collect::<Vec<_>>()
                    .join("\n"),
                json!({"items": items}),
                vec![],
                current,
            ))
        }
        BoardAction::Next { limit, area } => {
            let mut items = snapshot
                .items
                .values()
                .filter(|item| {
                    matches!(item.state.as_str(), "ready" | "open") && area.is_none()
                })
                .cloned()
                .collect::<Vec<_>>();
            items.sort_by(|a, b| {
                a.priority
                    .unwrap_or(i64::MAX)
                    .cmp(&b.priority.unwrap_or(i64::MAX))
                    .then_with(|| natural_cmp(a.id.as_str(), b.id.as_str()))
            });
            items.truncate(*limit);
            Ok((
                items
                    .iter()
                    .map(|item| format!("{}\t{}", item.id, item.title))
                    .collect::<Vec<_>>()
                    .join("\n"),
                json!({"items": items}),
                vec![],
                current,
            ))
        }
        BoardAction::Create {
            kind,
            id,
            title,
            priority,
            ..
        } => {
            if !matches!(kind, CreateKind::Story) {
                bail!("input/schema: session boards create items, not repository documents")
            }
            let id = id.clone().unwrap_or_else(|| {
                let max = snapshot
                    .items
                    .keys()
                    .filter_map(|id| id.as_str().strip_prefix("S-")?.parse::<u64>().ok())
                    .max()
                    .unwrap_or(0);
                format!("S-{}", max + 1)
            });
            let id = ItemId::new(id).map_err(|error| anyhow::anyhow!("input/schema: {error}"))?;
            if command.dry_run {
                return Ok((
                    format!("would create {id}"),
                    json!({"id": id, "title": title, "priority": priority, "dry_run": true}),
                    vec![],
                    current,
                ));
            }
            let next = board
                .create(
                    current,
                    request_id,
                    id.clone(),
                    title.clone(),
                    String::new(),
                    *priority,
                )
                .map_err(session_board_error)?;
            Ok((
                format!("created {id}"),
                session_snapshot_value(&next),
                vec![],
                next.revision,
            ))
        }
        BoardAction::Update {
            id,
            title,
            priority,
            note,
        } => {
            let id = ItemId::new(id).map_err(|error| anyhow::anyhow!("input/schema: {error}"))?;
            if command.dry_run {
                read_item(id.as_str())?;
                return Ok((
                    format!("would update {id}"),
                    json!({"id": id, "title": title, "priority": priority, "description": note, "dry_run": true}),
                    vec![],
                    current,
                ));
            }
            let next = board
                .update(
                    current,
                    request_id,
                    &id,
                    title.clone(),
                    *priority,
                    note.clone(),
                )
                .map_err(session_board_error)?;
            Ok((
                format!("updated {id}"),
                session_snapshot_value(&next),
                vec![],
                next.revision,
            ))
        }
        BoardAction::Transition { id, status }
        | BoardAction::Block {
            id,
            reason: status,
        } => {
            let to = if matches!(command.action, BoardAction::Block { .. }) {
                "blocked"
            } else {
                status
            };
            session_transition(command, board, &snapshot, request_id, id, to)
        }
        BoardAction::Start { id } => {
            session_transition(command, board, &snapshot, request_id, id, "in-progress")
        }
        BoardAction::Unblock { id } => {
            let target = if matches!(snapshot.profile, flux_datasource::board::BoardProfile::General)
            {
                "open"
            } else {
                "ready"
            };
            session_transition(command, board, &snapshot, request_id, id, target)
        }
        BoardAction::Done { id, .. } => {
            session_transition(command, board, &snapshot, request_id, id, "done")
        }
        BoardAction::Comment { id, text } => {
            let id = ItemId::new(id).map_err(|error| anyhow::anyhow!("input/schema: {error}"))?;
            if command.dry_run {
                read_item(id.as_str())?;
                return Ok((
                    format!("would comment on {id}"),
                    json!({"id": id, "comment": text, "dry_run": true}),
                    vec![],
                    current,
                ));
            }
            let next = board
                .comment(current, request_id, &id, text.clone())
                .map_err(session_board_error)?;
            Ok((
                format!("commented on {id}"),
                session_snapshot_value(&next),
                vec![],
                next.revision,
            ))
        }
        BoardAction::Evidence { id, evidence } => {
            let id = ItemId::new(id).map_err(|error| anyhow::anyhow!("input/schema: {error}"))?;
            if command.dry_run {
                read_item(id.as_str())?;
                return Ok((
                    format!("would record evidence for {id}"),
                    json!({"id": id, "evidence": evidence, "dry_run": true}),
                    vec![],
                    current,
                ));
            }
            let value = serde_json::from_str(evidence).unwrap_or_else(|_| json!(evidence));
            let next = board
                .record_evidence(current, request_id, &id, value)
                .map_err(session_board_error)?;
            Ok((
                format!("evidence recorded for {id}"),
                session_snapshot_value(&next),
                vec![],
                next.revision,
            ))
        }
        BoardAction::Check => Ok((
            format!("session board valid: {} item(s)", snapshot.items.len()),
            json!({"valid": true, "items": snapshot.items.len()}),
            vec![],
            current,
        )),
        BoardAction::Graph => {
            let nodes = snapshot
                .items
                .values()
                .map(|item| json!({"ref": item.id, "status": item.state}))
                .collect::<Vec<_>>();
            let edges = snapshot
                .items
                .values()
                .flat_map(|item| {
                    item.dependencies
                        .iter()
                        .map(move |dependency| json!({"from": dependency, "to": item.id}))
                })
                .collect::<Vec<_>>();
            Ok((
                format!("{} node(s), {} edge(s)", nodes.len(), edges.len()),
                json!({"nodes": nodes, "edges": edges}),
                vec![],
                current,
            ))
        }
        BoardAction::Stats { .. } | BoardAction::Report { .. } => {
            let done = snapshot
                .items
                .values()
                .filter(|item| item.state == "done")
                .count();
            let mut status = BTreeMap::new();
            for item in snapshot.items.values() {
                *status.entry(item.state.clone()).or_insert(0usize) += 1;
            }
            let data = json!({"schema": "flux.board-stats/v1", "stories": ratio(done, snapshot.items.len()), "implementation": ratio(done, snapshot.items.len()), "criteria": absent_ratio(), "tasks": absent_ratio(), "status": status, "documents": {"vision":{"present":false},"roadmap":{"present":false},"decisions":{"total":0},"designs":{"total":0}}});
            Ok((stats_human(&data), data, vec![], current))
        }
        BoardAction::Export { .. } => {
            let data = session_snapshot_value(&snapshot);
            Ok((serde_json::to_string_pretty(&data)?, data, vec![], current))
        }
        BoardAction::Call { .. }
        | BoardAction::Render
        | BoardAction::Sync
        | BoardAction::Import { .. }
        | BoardAction::Vision { .. }
        | BoardAction::Roadmap { .. }
        | BoardAction::Decision { .. }
        | BoardAction::Design { .. } => bail!(
            "input/schema: this operation is not available on the session backend; inspect `flux board schema`"
        ),
    }
}

fn session_transition(
    command: &BoardCommand,
    board: &flux_capabilities::SessionBoard,
    snapshot: &flux_capabilities::SessionBoardSnapshot,
    request_id: Option<&str>,
    id: &str,
    to: &str,
) -> Result<(String, Value, Vec<String>, u64)> {
    use flux_datasource::board::ItemId;
    let id = ItemId::new(id).map_err(|error| anyhow::anyhow!("input/schema: {error}"))?;
    let item = snapshot
        .items
        .get(&id)
        .with_context(|| format!("not-found: item {id}"))?;
    if !flux_capabilities::SessionBoard::transition_allowed(snapshot.profile, &item.state, to) {
        bail!(
            "conflict/precondition: profile {:?} refuses transition {} -> {to}",
            snapshot.profile,
            item.state
        )
    }
    if command.dry_run {
        return Ok((
            format!("would transition {id} to {to}"),
            json!({"id": id, "from": item.state, "to": to, "dry_run": true}),
            vec![],
            snapshot.revision,
        ));
    }
    let next = board
        .transition(snapshot.revision, request_id, &id, to)
        .map_err(session_board_error)?;
    Ok((
        format!("{id} is now {to}"),
        session_snapshot_value(&next),
        vec![],
        next.revision,
    ))
}

fn run_board_action(
    command: &BoardCommand,
    root: &Path,
    request: Option<Value>,
    revision: &str,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let board_id = command.board.as_deref().unwrap_or("default");
    match &command.action {
        BoardAction::Skill => {
            let skill = board_skill();
            Ok((
                skill.clone(),
                skill_json("flux-board", &skill, "board"),
                vec![],
                None,
            ))
        }
        BoardAction::Schema => Ok((
            "Use `--output json` for the flux.cli/v1 board schema.".into(),
            family_schema("board", board_operations()),
            vec![],
            None,
        )),
        BoardAction::Init { scaffold } => {
            let stories = root.join("docs/stories");
            let board = stories.join("README.md");
            if !command.dry_run {
                fs::create_dir_all(&stories).context("create docs/stories")?;
                if *scaffold && !board.exists() {
                    fs::write(&board, format!("# Board\n\n{BEGIN}\n{END}\n"))
                        .context("write board scaffold")?;
                }
            }
            let data = json!({
                "board": board_id,
                "scope": command.scope,
                "profile": command.profile,
                "backend": "track",
                "root": display_path(root),
                "scaffold": scaffold,
                "dry_run": command.dry_run,
            });
            Ok((
                format!("board {board_id} initialized"),
                data,
                vec![],
                changed_revision(root, command.dry_run)?,
            ))
        }
        BoardAction::List => {
            let data = json!({"boards": [{
                "id": board_id, "scope": command.scope, "profile": command.profile,
                "backend": "track", "root": display_path(root), "revision": revision
            }]});
            Ok((
                format!(
                    "{board_id}\ttrack\t{:?}\t{:?}",
                    command.scope, command.profile
                ),
                data,
                vec![],
                None,
            ))
        }
        BoardAction::Show => {
            let stories = read_board_items(command, root)?;
            let data = json!({
                "id": board_id, "scope": command.scope, "profile": command.profile,
                "backend": "track", "root": display_path(root), "revision": revision,
                "items": stories.len(), "documents": document_counts(root)
            });
            Ok((
                format!(
                    "board {board_id}: {} item(s), revision {revision}",
                    stories.len()
                ),
                data,
                vec![],
                None,
            ))
        }
        BoardAction::Items => list_items(command, root, None, None, None),
        BoardAction::Get { id } => {
            let story = get_board_item(command, root, id)?;
            Ok((
                story.body.clone(),
                serde_json::to_value(story)?,
                vec![],
                None,
            ))
        }
        BoardAction::Query { status, area, text } => list_items(
            command,
            root,
            status.as_deref(),
            area.as_deref(),
            text.as_deref(),
        ),
        BoardAction::Next { limit, area } => {
            let all = read_board_items(command, root)?;
            let states = all
                .iter()
                .map(|story| (story.id.clone(), story.status.clone()))
                .collect::<BTreeMap<_, _>>();
            let mut stories: Vec<_> = all
                .into_iter()
                .filter(|story| {
                    story.status == "ready"
                        && area
                            .as_deref()
                            .is_none_or(|area| story.areas.iter().any(|value| value == area))
                        && story.dependencies.iter().all(|dependency| {
                            states
                                .get(dependency)
                                .is_some_and(|status| status == "done")
                        })
                })
                .collect();
            sort_ready(&mut stories);
            stories.truncate(*limit);
            item_result(stories)
        }
        BoardAction::Create {
            kind,
            id,
            title,
            pillar,
            status,
            priority,
            epic,
            areas,
            design,
            note,
        } => create_item(
            command,
            root,
            CreateItemInput {
                kind: *kind,
                id: id.as_deref(),
                title,
                pillar,
                status,
                priority: *priority,
                epic: epic.as_deref(),
                areas,
                design: design.as_deref(),
                note: note.as_deref(),
            },
        ),
        BoardAction::Update {
            id,
            title,
            priority,
            note,
        } => {
            let mut fields = Vec::new();
            if let Some(value) = title {
                fields.push(("title", value.clone()));
            }
            if let Some(value) = priority {
                fields.push(("priority", value.to_string()));
            }
            if let Some(value) = note {
                fields.push(("note", yaml_quote(value)));
            }
            mutate_story(command, root, id, fields, None)
        }
        BoardAction::Transition { id, status } => transition(command, root, id, status, None),
        BoardAction::Start { id } => transition(command, root, id, "in-progress", None),
        BoardAction::Block { id, reason } => transition(
            command,
            root,
            id,
            "blocked",
            Some(("blocked_reason", reason)),
        ),
        BoardAction::Unblock { id } => transition(command, root, id, "ready", None),
        BoardAction::Done {
            id,
            override_reason,
            changelog,
        } => complete_story(
            command,
            root,
            id,
            override_reason.as_deref(),
            changelog.as_deref(),
        ),
        BoardAction::Comment { id, text } => {
            append_story_section(command, root, id, "Comments", text)
        }
        BoardAction::Evidence { id, evidence } => {
            append_story_section(command, root, id, "Evidence", evidence)
        }
        BoardAction::Check => {
            if command.scope == BoardScopeArg::Workspace && command.board.is_none() {
                check_workspace_board(root)
            } else {
                check_board(root)
            }
        }
        BoardAction::Render => {
            let rendered = render_track(root, command.dry_run)?;
            Ok((
                rendered.0,
                rendered.1,
                rendered.2,
                changed_revision(root, command.dry_run)?,
            ))
        }
        BoardAction::Sync => {
            check_board(root)?;
            let rendered = render_track(root, command.dry_run)?;
            Ok((
                rendered.0,
                rendered.1,
                rendered.2,
                changed_revision(root, command.dry_run)?,
            ))
        }
        BoardAction::Graph => graph(command, root),
        BoardAction::Stats { history, since } => {
            let data = stats(command, root, *history, since.as_deref())?;
            Ok((stats_human(&data), data, vec![], None))
        }
        BoardAction::Report {
            format,
            out,
            history,
        } => {
            let data = stats(command, root, *history, None)?;
            let body = render_report(&data, *format)?;
            if let Some(path) = out {
                if !command.dry_run {
                    fs::write(root.join(path), &body)?;
                }
            }
            Ok((body, data, vec![], None))
        }
        BoardAction::Export { out } => {
            let data = json!({
                "schema": "flux.board-export/v1", "board": board_id,
                "scope": command.scope, "profile": command.profile,
                "items": export_items(command, root)?, "documents": export_documents(root)?
            });
            let body = serde_json::to_string_pretty(&data)?;
            if let Some(path) = out {
                if !command.dry_run {
                    fs::write(root.join(path), &body)?;
                }
            }
            Ok((body, data, vec![], None))
        }
        BoardAction::Import { path } => {
            let value = read_json_path(path)?;
            import_board(command, root, &value)
        }
        BoardAction::Vision { action } => singleton_doc(command, root, "vision", action),
        BoardAction::Roadmap { action } => singleton_doc(command, root, "roadmap", action),
        BoardAction::Decision { action } => decision_doc(command, root, action),
        BoardAction::Design { action } => design_doc(command, root, action),
        BoardAction::Call { target, operation } => {
            let (binding, operation) = match operation {
                Some(operation) => (Some(target.as_str()), operation.as_str()),
                None => (command.board.as_deref(), target.as_str()),
            };
            if let (Some(selected), Some(binding)) = (command.board.as_deref(), binding) {
                if selected != binding {
                    bail!("input/schema: --board and the positional board binding select different boards")
                }
            }
            board_call(command, root, operation, request)
        }
    }
}

pub(super) fn run_fleet(command: FleetCommand) -> Result<()> {
    let output = command.output;
    match run_fleet_checked(command) {
        Ok(()) => Ok(()),
        Err(error) => emit_error(output, error),
    }
}

fn run_fleet_checked(command: FleetCommand) -> Result<()> {
    let request = load_request(command.request.as_deref())?;
    let envelope_request_id = request_id_from(request.as_ref())?;
    let root = confined_root(&command.root)?;
    validate_fleet_common(&command, request.as_ref())?;
    let mut state = read_fleet_state(&root)?;
    let fingerprint = request_fingerprint(&command.action, request.as_ref());
    if let Some(key) = command.idempotency_key.as_deref() {
        if let Some(stored) = state.idempotency.get(key) {
            if stored.fingerprint != fingerprint {
                bail!("conflict/precondition: idempotency key was already used for a different fleet request");
            }
            return emit(
                command.output,
                &stored.human,
                stored.data.clone(),
                stored.warnings.clone(),
                Some(&stored.revision),
                envelope_request_id.as_deref(),
            );
        }
    }
    check_revision(command.if_revision.as_deref(), &state.revision.to_string())?;
    let result = run_fleet_action(&command, &root, state.clone(), request);
    match result {
        Ok((human, data, warnings, revision)) => {
            if fleet_action_mutates(&command.action) && !command.dry_run {
                if let Some(key) = command.idempotency_key.as_ref() {
                    state = read_fleet_state(&root)?;
                    state.idempotency.insert(
                        key.clone(),
                        StoredResult {
                            fingerprint,
                            human: human.clone(),
                            data: data.clone(),
                            warnings: warnings.clone(),
                            revision: revision.to_string(),
                        },
                    );
                    write_fleet_state(&root, &state)?;
                }
            }
            emit(
                command.output,
                &human,
                data,
                warnings,
                Some(&revision.to_string()),
                envelope_request_id.as_deref(),
            )
        }
        Err(error) => Err(error),
    }
}

fn run_fleet_action(
    command: &FleetCommand,
    root: &Path,
    mut state: FleetState,
    request: Option<Value>,
) -> Result<(String, Value, Vec<String>, u64)> {
    match &command.action {
        FleetAction::Skill => {
            let skill = fleet_skill();
            Ok((
                skill.clone(),
                skill_json("flux-fleet", &skill, "fleet"),
                vec![],
                state.revision,
            ))
        }
        FleetAction::Schema => Ok((
            "Use `--output json` for the flux.cli/v1 fleet schema.".into(),
            family_schema("fleet", fleet_operations()),
            vec![],
            state.revision,
        )),
        FleetAction::Init {
            max_workers,
            max_wave,
            max_rework,
        } => {
            validate_fleet_limits(*max_workers, *max_wave, *max_rework)?;
            state.max_workers = *max_workers;
            state.max_wave = *max_wave;
            state.max_rework = *max_rework;
            state.revision += 1;
            if !command.dry_run {
                let system = guarded_system(root)?;
                if system.read_optional_text(".flux/fleet.toml")?.is_none() {
                    system.write_file_atomic(".flux/fleet.toml", &format!("schema = \"flux.fleet/v1\"\nmax_workers = {max_workers}\nmax_wave = {max_wave}\nmax_rework = {max_rework}\ndecision_mode = \"human\" # or \"auto\" for an independent adversarial decision agent\nallow_ad_hoc_agents = true\nworktree_root = \".flux/fleet/worktrees\"\n\n# [main]\n# instructions = \".flux/fleet/main.md\"\n# model = \"codex/gpt-5.6-sol\"\n\n# [[agent_templates]]\n# id = \"story-worker\"\n# role = \"writer\"\n# instructions = \".flux/fleet/agents/story-worker.md\"\n# mode = \"write\"\n# capabilities = [\"read\", \"edit\", \"git\", \"shell\"]\n# fences = [\".git/**\", \".flux/fleet/**\"]\n# max_instances = {max_workers}\n\n# [[repositories]]\n# id = \"repo\"\n# root = \".\"\n# board = \"default\"\n# canonical_ref = \"origin/main\"\n# gate = [\"cargo\", \"test\", \"--workspace\"]\n"))?;
                }
                write_fleet_state(root, &state)?;
                append_fleet_event(
                    root,
                    "fleet.initialized",
                    json!({"max_workers": max_workers, "max_wave": max_wave, "max_rework": max_rework}),
                )?;
            }
            Ok((
                "fleet initialized".into(),
                serde_json::to_value(&state)?,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Doctor | FleetAction::Validate => {
            let config = root.join(".flux/fleet.toml");
            let mut errors = Vec::new();
            if !config.exists() {
                errors.push("missing .flux/fleet.toml".to_string());
            }
            validate_fleet_limits(state.max_workers, state.max_wave, state.max_rework)?;
            if config.exists() {
                read_fleet_config(root)?;
            }
            let data = json!({"valid": errors.is_empty(), "errors": errors, "state": state});
            if !data["valid"].as_bool().unwrap_or(false) {
                bail!("validation/gate: missing .flux/fleet.toml (run `flux fleet init`)");
            }
            Ok((
                "fleet configuration valid".into(),
                data,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Refresh => {
            let data = fleet_sources(root)?;
            Ok((
                "fleet sources inspected; no checkout was modified".into(),
                data,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Start => {
            state.running = true;
            state.main_agent.status = "running".into();
            state.revision += 1;
            persist_fleet_mutation(
                command,
                root,
                &state,
                "fleet.started",
                json!({"main_agent": state.main_agent}),
            )?;
            Ok((
                "fleet supervisor and main coordinator started".into(),
                serde_json::to_value(&state)?,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Stop => {
            state.running = false;
            state.main_agent.status = "stopped".into();
            state.revision += 1;
            persist_fleet_mutation(
                command,
                root,
                &state,
                "fleet.stopped",
                json!({"main_agent": state.main_agent}),
            )?;
            Ok((
                "fleet supervisor stopped".into(),
                serde_json::to_value(&state)?,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Goal { action } => fleet_goal(command, root, state, action),
        FleetAction::Ingest {
            text,
            source,
            from,
            wait,
        } => {
            if text.trim().is_empty() {
                bail!("input/schema: coordinator intake text cannot be empty")
            }
            if from.trim().is_empty() {
                bail!("input/schema: coordinator intake source identity cannot be empty")
            }
            state.revision += 1;
            state.main_agent.intake_sequence += 1;
            let id = format!("intake-{}", state.main_agent.intake_sequence);
            let intake = json!({
                "id": id,
                "target": "main",
                "source": source,
                "from": redact(from),
                "text": redact(text),
                "ack": "accepted",
                "goals_revision": state.main_agent.goals_revision,
            });
            state.intake.insert(id.clone(), intake.clone());
            persist_fleet_mutation(
                command,
                root,
                &state,
                "coordinator.intake.accepted",
                intake.clone(),
            )?;
            if *wait != AckLevel::Accepted {
                if !state.running {
                    bail!("conflict/precondition: main coordinator is stopped; run `flux fleet start`")
                }
                let request = format!(
                    "Ingest {} requirement from {} and update the roadmap/board only when the authored contracts require it:\n{}",
                    match source {
                        IntakeSource::User => "user",
                        IntakeSource::Agent => "agent follow-up",
                        IntakeSource::Automation => "automation",
                    },
                    from,
                    text
                );
                let spec = main_turn_spec(root, &state, request)?;
                let receipt =
                    execute_and_record_agent_turn(command, root, &mut state, spec, Some(&id))?;
                return Ok((
                    format!("{id} completed by main coordinator"),
                    json!({"intake": state.intake[&id], "receipt": receipt, "requested_ack": wait}),
                    vec![],
                    state.revision,
                ));
            }
            Ok((
                format!("{id} accepted by main coordinator"),
                intake,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Spawn {
            template,
            role,
            instructions,
            instructions_file,
            model,
            item,
            mode,
            name,
            capabilities,
            fences,
        } => fleet_spawn(
            command,
            root,
            state,
            SpawnOptions {
                template: template.as_deref(),
                role: role.as_deref(),
                instructions: instructions.as_deref(),
                instructions_file: instructions_file.as_deref(),
                model: model.as_deref(),
                item: item.as_deref(),
                mode: *mode,
                name: name.as_deref(),
                capabilities,
                fences,
            },
        ),
        FleetAction::Status | FleetAction::Dashboard => {
            let data = json!({"state": state, "sources": fleet_sources(root)?, "schedule": fleet_schedule(root)?, "human_decisions": open_decisions(root)?});
            Ok((fleet_status_human(&data), data, vec![], state.revision))
        }
        FleetAction::Schedule => {
            let data = fleet_schedule(root)?;
            Ok((schedule_human(&data), data, vec![], state.revision))
        }
        FleetAction::Decisions { auto } => {
            let decisions = open_decisions(root)?;
            let configured = if root.join(".flux/fleet.toml").is_file() {
                Some(read_fleet_config(root)?)
            } else {
                None
            };
            let configured_mode = configured
                .as_ref()
                .map(|config| config.decision_mode)
                .unwrap_or(DecisionMode::Human);
            let auto = *auto || configured_mode == DecisionMode::Auto;
            let mut auto_workers = Vec::new();
            if auto && !decisions.as_array().is_none_or(Vec::is_empty) {
                state.revision += 1;
                for decision in decisions.as_array().into_iter().flatten() {
                    let decision_ref = decision["ref"].as_str().unwrap_or("unknown/unknown");
                    let worker = format!(
                        "decision-{}",
                        decision_ref
                            .chars()
                            .map(|character| if character.is_ascii_alphanumeric() {
                                character
                            } else {
                                '-'
                            })
                            .collect::<String>()
                    );
                    state.agents.entry(worker.clone()).or_insert_with(|| {
                        json!({
                            "id": worker,
                            "role": "adversarial-decision-agent",
                            "created_by": "main",
                            "fresh_context": true,
                            "status": "accepted",
                            "decision": decision,
                            "recommendation_must_be_challenged": true,
                            "goals_revision": state.main_agent.goals_revision,
                            "goals": state.goals,
                            "instructions": "Act as a fresh adversarial decision agent. Evaluate every structured option and trade-off against the supplied scoped goals. Challenge the proposer recommendation, choose independently, record rationale, and use `flux board decision decide` only when the evidence supports one declared option.",
                            "model": configured.as_ref().and_then(|config| config.main.model.as_deref()),
                        })
                    });
                    auto_workers.push((worker, decision.clone()));
                }
                persist_fleet_mutation(
                    command,
                    root,
                    &state,
                    "decision.review.queued",
                    json!({"decisions": decisions, "mode": "auto", "coordinator": "main"}),
                )?;
            }
            let mut auto_receipts = Vec::new();
            if auto && state.running && !command.dry_run {
                for (worker, decision) in &auto_workers {
                    let request = format!(
                        "Resolve this decision autonomously. Inspect its linked board context first, challenge the recommendation, then either record one declared option with a concrete rationale or leave it open and explain what evidence is missing:\n{}",
                        serde_json::to_string_pretty(decision)?
                    );
                    let spec = addressed_turn_spec(root, &state, worker, request)?;
                    auto_receipts.push(execute_and_record_agent_turn(
                        command, root, &mut state, spec, None,
                    )?);
                }
            }
            let remaining = if auto_receipts.is_empty() {
                decisions.clone()
            } else {
                open_decisions(root)?
            };
            let human = decisions
                .as_array()
                .into_iter()
                .flatten()
                .map(|decision| {
                    format!(
                        "{}\t{}",
                        decision["ref"].as_str().unwrap_or_default(),
                        decision["question"].as_str().unwrap_or_default()
                    )
                })
                .collect::<Vec<_>>()
                .join("\n");
            Ok((
                human,
                json!({"decisions": remaining, "attention_required": !remaining.as_array().is_none_or(Vec::is_empty), "mode": if auto {"auto"} else {"human"}, "auto_reviews_queued": auto, "auto_receipts": auto_receipts}),
                vec![],
                state.revision,
            ))
        }
        FleetAction::Run {
            items,
            prepare_only,
        } => {
            if !state.running {
                bail!("conflict/precondition: fleet supervisor is stopped; run `flux fleet start`");
            }
            if items.len() > state.max_wave {
                bail!(
                    "validation/gate: wave has {} items, maximum is {}",
                    items.len(),
                    state.max_wave
                );
            }
            let selected = if items.is_empty() {
                select_ready_items(root, state.max_wave)?
            } else {
                validate_board_refs(items)?;
                items.clone()
            };
            if selected.is_empty() {
                bail!("not-found: no dependency-satisfied ready items");
            }
            let config = read_fleet_config(root)?;
            let template = config
                .agent_templates
                .iter()
                .find(|template| template.id == "story-worker");
            let instructions = match template {
                Some(template) => read_configured_instructions(
                    root,
                    &template.instructions,
                    "story-worker instructions",
                )?,
                None => "Implement exactly one assigned story in the current isolated worktree. Read its Goal, Acceptance, linked design, applicable decisions and AGENTS.md. Add failing-first evidence for behavior, run targeted checks, commit the exact story-sized result, and return a concise handoff. Never integrate, push, publish, deploy, or edit the fleet ledger.".into(),
            };
            let role = template
                .map(|template| template.role.as_str())
                .unwrap_or("writer");
            let mode = template
                .map(|template| template.mode)
                .unwrap_or(FleetTaskMode::Write);
            let requested_capabilities = template
                .map(|template| template.capabilities.clone())
                .unwrap_or_else(|| {
                    DEFAULT_STORY_CAPABILITIES
                        .iter()
                        .map(|capability| (*capability).to_string())
                        .collect()
                });
            let (capabilities, operations) =
                normalize_worker_capabilities(mode, &requested_capabilities)?;
            let template_fences = template
                .map(|template| template.fences.clone())
                .unwrap_or_default();
            let model = template.and_then(|template| template.model.clone());
            let wave = format!("wave-{}", state.revision + 1);
            let topology = prepare_wave_worktrees(command, root, &wave, &selected)?;
            state.revision += 1;
            for (index, item) in selected.iter().enumerate() {
                let worker = format!("{}-worker-{}", wave, index + 1);
                let assignment = topology["repositories"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .flat_map(|repository| repository["stories"].as_array().into_iter().flatten())
                    .find(|story| story["board_ref"].as_str() == Some(item.as_str()))
                    .cloned()
                    .unwrap_or(Value::Null);
                let worktree = PathBuf::from(
                    assignment["worktree"]
                        .as_str()
                        .context("validation/gate: story worker assignment has no worktree")?,
                );
                let repository_id = assignment["repository"]
                    .as_str()
                    .or_else(|| item.split_once('/').map(|(repository, _)| repository));
                let repository_fences = repository_id
                    .and_then(|repository_id| {
                        config
                            .repositories
                            .iter()
                            .find(|repository| repository.id == repository_id)
                    })
                    .map(|repository| repository.fences.clone())
                    .unwrap_or_default();
                let fences =
                    normalize_fences(template_fences.iter().cloned().chain(repository_fences));
                let read_roots = Vec::<PathBuf>::new();
                let capability_set = capability_set_manifest(
                    mode,
                    &capabilities,
                    &operations,
                    &worktree,
                    &read_roots,
                    &fences,
                );
                state.agents.insert(
                    worker.clone(),
                    json!({
                        "id": worker,
                        "role": role,
                        "parent": "main",
                        "created_by": "main",
                        "board_ref": item,
                        "status": "accepted",
                        "transport": "flux-local",
                        "session": format!("{wave}-session-{}", index + 1),
                        "assignment": assignment,
                        "template": template.map(|template| template.id.as_str()),
                        "model": model,
                        "mode": mode,
                        "instructions": redact(&instructions),
                        "capabilities": capabilities,
                        "fences": fences,
                        "writable_root": display_path(&worktree),
                        "read_roots": read_roots.iter().map(|root| display_path(root)).collect::<Vec<_>>(),
                        "capability_set": capability_set,
                    }),
                );
            }
            state.waves.insert(wave.clone(), json!({"id": wave, "items": selected, "status": "accepted", "coordinator": "main", "goals_revision": state.main_agent.goals_revision, "topology": topology, "apply_eligible": false}));
            persist_fleet_mutation(
                command,
                root,
                &state,
                "wave.accepted",
                json!({"wave": wave, "items": selected, "coordinator": "main", "topology": topology}),
            )?;
            if !*prepare_only && !command.dry_run {
                let workers = state
                    .agents
                    .iter()
                    .filter(|(_, agent)| {
                        agent["assignment"]["wave"].as_str() == Some(wave.as_str())
                            || agent["id"]
                                .as_str()
                                .is_some_and(|id| id.starts_with(&format!("{wave}-worker-")))
                    })
                    .map(|(id, agent)| (id.clone(), agent.clone()))
                    .collect::<Vec<_>>();
                let mut specs = Vec::new();
                for (worker, agent) in workers {
                    let assignment = &agent["assignment"];
                    let worktree = PathBuf::from(
                        assignment["worktree"]
                            .as_str()
                            .context("validation/gate: story worker assignment has no worktree")?,
                    );
                    let item = agent["board_ref"].as_str().unwrap_or("unknown/unknown");
                    let request = story_worker_request(item, assignment, &worktree);
                    specs.push(addressed_turn_spec(root, &state, &worker, request)?);
                }
                state.revision += 1;
                for spec in &specs {
                    if let Some(agent) = state.agents.get_mut(&spec.id) {
                        agent["status"] = json!("working");
                    }
                }
                persist_fleet_mutation(
                    command,
                    root,
                    &state,
                    "wave.agent-turns.delivered",
                    json!({"wave":wave,"agents":specs.iter().map(|spec|spec.id.as_str()).collect::<Vec<_>>(),"max_workers":state.max_workers}),
                )?;

                let runtime = tokio::runtime::Handle::current();
                let goals = scoped_goals(&state);
                let mut outcomes = Vec::new();
                for batch in specs.chunks(state.max_workers) {
                    let batch_outcomes = std::thread::scope(|scope| {
                        let handles = batch
                            .iter()
                            .cloned()
                            .map(|spec| {
                                let runtime = runtime.clone();
                                let goals = goals.clone();
                                scope.spawn(move || {
                                    let id = spec.id.clone();
                                    let result = execute_agent_turn_with_runtime(
                                        root,
                                        &spec,
                                        &goals,
                                        Some(&runtime),
                                    );
                                    (id, result)
                                })
                            })
                            .collect::<Vec<_>>();
                        handles
                            .into_iter()
                            .map(|handle| {
                                handle.join().unwrap_or_else(|_| {
                                    (
                                        "unknown".into(),
                                        Err(anyhow::anyhow!(
                                            "transient-worker: story agent thread panicked"
                                        )),
                                    )
                                })
                            })
                            .collect::<Vec<_>>()
                    });
                    outcomes.extend(batch_outcomes);
                }
                let mut receipts = Vec::new();
                let mut errors = Vec::new();
                for (id, outcome) in outcomes {
                    match outcome {
                        Ok(receipt) => {
                            if let Some(agent) = state.agents.get_mut(&id) {
                                agent["status"] = json!("completed");
                                agent["runtime_session"] = receipt["session"].clone();
                                agent["session"] = receipt["session"].clone();
                                agent["last_turn"] = receipt.clone();
                                agent["last_error"] = Value::Null;
                            }
                            receipts.push(receipt);
                        }
                        Err(error) => {
                            let message = redact(&error.to_string());
                            if let Some(agent) = state.agents.get_mut(&id) {
                                agent["status"] = json!("failed");
                                agent["last_error"] = json!(message);
                            }
                            errors.push(json!({"agent":id,"error":message}));
                        }
                    }
                }
                if let Some(record) = state.waves.get_mut(&wave) {
                    record["status"] = json!(if errors.is_empty() {
                        "awaiting-handoffs"
                    } else {
                        "agent-turn-failed"
                    });
                    record["agent_turns"] = json!(receipts);
                    record["agent_errors"] = json!(errors);
                }
                state.revision += 1;
                persist_fleet_mutation(
                    command,
                    root,
                    &state,
                    if errors.is_empty() {
                        "wave.agent-turns.completed"
                    } else {
                        "wave.agent-turns.failed"
                    },
                    json!({"wave": wave, "receipts": receipts, "errors":errors}),
                )?;
                if !errors.is_empty() {
                    bail!(
                        "transient-worker: {} of {} story agent turn(s) failed; inspect fleet events",
                        errors.len(),
                        specs.len()
                    )
                }
                return Ok((
                    format!("{wave} agents completed; handoffs required"),
                    json!({"wave": wave, "items": selected, "ack": "completed", "topology": topology, "receipts": receipts}),
                    vec![],
                    state.revision,
                ));
            }
            Ok((
                format!("{wave} accepted: {} item(s)", selected.len()),
                json!({"wave": wave, "items": selected, "ack": "accepted", "prepare_only": prepare_only, "topology": topology}),
                vec![],
                state.revision,
            ))
        }
        FleetAction::Handoff {
            wave,
            item,
            commit,
            worker,
            session,
            write_set,
            test_argv,
            failing_before,
            passing_after,
            no_failing_test_reason,
            summary,
        } => fleet_handoff(
            command,
            root,
            state,
            HandoffInput {
                wave,
                item,
                commit,
                worker: worker.as_deref(),
                session: session.as_deref(),
                write_set,
                test_argv,
                failing_before: *failing_before,
                passing_after: *passing_after,
                no_failing_test_reason: no_failing_test_reason.as_deref(),
                summary,
            },
        ),
        FleetAction::Rework {
            wave,
            item,
            reviewer,
            reviewed_commit,
            paths,
            command_outputs,
            invariants,
        } => fleet_rework(
            command,
            root,
            state,
            ReworkInput {
                wave,
                item,
                reviewer,
                reviewed_commit,
                paths,
                command_outputs,
                invariants,
            },
        ),
        FleetAction::Integrate { wave } => integrate_wave(command, root, state, wave),
        FleetAction::Task {
            target,
            instruction,
            mode,
            wait,
        } => {
            if instruction.trim().is_empty() {
                bail!("input/schema: task needs an instruction");
            }
            state.revision += 1;
            let id = format!("task-{}", state.revision);
            state.main_agent.intake_sequence += 1;
            let event = json!({
                "id": id,
                "target": "main",
                "requested_target": target,
                "instruction": redact(instruction),
                "mode": mode,
                "ack": "accepted",
                "goals_revision": state.main_agent.goals_revision,
            });
            state.intake.insert(id.clone(), event.clone());
            persist_fleet_mutation(command, root, &state, "task.accepted", event.clone())?;
            if *wait != AckLevel::Accepted {
                if !state.running {
                    bail!("conflict/precondition: main coordinator is stopped; run `flux fleet start`")
                }
                let request = format!(
                    "Coordinate this {:?} task requested for {target}. Keep it read-only unless the board and explicit mode authorize a writer/worktree:\n{instruction}",
                    mode
                );
                let spec = main_turn_spec(root, &state, request)?;
                let receipt =
                    execute_and_record_agent_turn(command, root, &mut state, spec, Some(&id))?;
                return Ok((
                    format!("{id} completed by main coordinator for {target}"),
                    json!({"task": state.intake[&id], "receipt": receipt, "requested_ack": wait}),
                    vec![],
                    state.revision,
                ));
            }
            Ok((
                format!("{id} accepted by main coordinator for {target}"),
                event,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Message {
            target,
            message,
            wait,
        } => {
            if message.trim().is_empty() {
                bail!("input/schema: fleet message cannot be empty")
            }
            if target != "main" && !state.agents.contains_key(target) {
                bail!("not-found: admitted fleet agent {target}")
            }
            state.revision += 1;
            state.main_agent.intake_sequence += 1;
            let id = format!("message-{}", state.main_agent.intake_sequence);
            let event = json!({"id": id, "target": target, "message": redact(message), "ack": "accepted", "requested_ack": wait});
            state.intake.insert(id.clone(), event.clone());
            persist_fleet_mutation(command, root, &state, "message.accepted", event.clone())?;
            if *wait != AckLevel::Accepted {
                if !state.running {
                    bail!("conflict/precondition: fleet supervisor is stopped; run `flux fleet start`")
                }
                let spec = addressed_turn_spec(root, &state, target, message.clone())?;
                let receipt =
                    execute_and_record_agent_turn(command, root, &mut state, spec, Some(&id))?;
                return Ok((
                    format!("message for {target}: completed"),
                    json!({"message": state.intake[&id], "receipt": receipt, "requested_ack": wait}),
                    vec![],
                    state.revision,
                ));
            }
            Ok((
                format!("message for {target}: accepted"),
                event,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Cancel { target } => {
            fleet_control_mutation(command, root, state, "cancelled", target)
        }
        FleetAction::Resume { target } => {
            let target = target.as_deref().unwrap_or("main");
            state.running = true;
            let pending = state
                .intake
                .values()
                .filter(|item| item["ack"].as_str() == Some("accepted"))
                .map(|item| {
                    format!(
                        "- {}: {}",
                        item["id"].as_str().unwrap_or("unknown"),
                        item["text"]
                            .as_str()
                            .or_else(|| item["instruction"].as_str())
                            .or_else(|| item["message"].as_str())
                            .unwrap_or("resume")
                    )
                })
                .collect::<Vec<_>>();
            let request = if pending.is_empty() {
                "Resume from the durable manifest and board. Inspect in-flight waves, blocked decisions, failed/crashed turns and dependency-satisfied work; continue only previously authorized work.".into()
            } else {
                format!(
                    "Resume from the durable manifest and process these accepted inputs in order:\n{}",
                    pending.join("\n")
                )
            };
            let spec = addressed_turn_spec(root, &state, target, request)?;
            let receipt = execute_and_record_agent_turn(command, root, &mut state, spec, None)?;
            for intake in state.intake.values_mut() {
                if intake["ack"].as_str() == Some("accepted") {
                    intake["ack"] = json!("completed");
                    intake["receipt"] = receipt.clone();
                }
            }
            state.revision += 1;
            persist_fleet_mutation(
                command,
                root,
                &state,
                "fleet.resumed",
                json!({"target": target, "receipt": receipt}),
            )?;
            Ok((
                format!("{target} resumed from durable state"),
                json!({"target": target, "ack": "completed", "receipt": receipt}),
                vec![],
                state.revision,
            ))
        }
        FleetAction::Note { text } => {
            state.revision += 1;
            let event = json!({"text": redact(text)});
            persist_fleet_mutation(command, root, &state, "coordinator.note", event.clone())?;
            Ok((
                "coordinator note recorded".into(),
                event,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Events { follow, limit } => {
            if *follow && command.output != AgentOutput::Ndjson {
                bail!("input/schema: events --follow requires --output ndjson");
            }
            let events = read_event_lines(root, *limit)?;
            if command.output == AgentOutput::Ndjson {
                for event in &events {
                    println!("{}", serde_json::to_string(event)?);
                }
                return Ok((String::new(), Value::Null, vec![], state.revision));
            }
            Ok((
                events
                    .iter()
                    .map(|v| v.to_string())
                    .collect::<Vec<_>>()
                    .join("\n"),
                json!({"events": events, "bounded": true, "limit": limit}),
                vec![],
                state.revision,
            ))
        }
        FleetAction::Logs { target, limit } => {
            let mut events = read_event_lines(root, *limit)?;
            if let Some(target) = target {
                events.retain(|event| event.to_string().contains(target));
            }
            Ok((
                events
                    .iter()
                    .map(|v| v.to_string())
                    .collect::<Vec<_>>()
                    .join("\n"),
                json!({"events": events, "bounded": true, "limit": limit}),
                vec![],
                state.revision,
            ))
        }
        FleetAction::Agents => Ok((
            std::iter::once("main".to_string())
                .chain(state.agents.keys().cloned())
                .collect::<Vec<_>>()
                .join("\n"),
            json!({"main_agent": state.main_agent, "workers": state.agents}),
            vec![],
            state.revision,
        )),
        FleetAction::Worktrees => {
            let data = fleet_worktrees(root)?;
            Ok((worktrees_human(&data), data, vec![], state.revision))
        }
        FleetAction::Inspect {
            view,
            target,
            limit,
        } => {
            let data = fleet_inspect(root, &state, *view, target.as_deref(), *limit)?;
            Ok((
                serde_json::to_string_pretty(&data)?,
                data,
                vec![],
                state.revision,
            ))
        }
        FleetAction::Apply { wave } => apply_wave(command, root, state, wave),
        FleetAction::Call { operation } => fleet_call(command, root, state, operation, request),
    }
}

