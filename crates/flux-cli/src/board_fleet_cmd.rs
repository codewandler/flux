fn create_item(
    command: &BoardCommand,
    root: &Path,
    kind: CreateKind,
    id: Option<&str>,
    title: &str,
    priority: Option<i64>,
    epic: Option<&str>,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let (dir, prefix) = match kind {
        CreateKind::Story => (root.join("docs/stories"), "C"),
        CreateKind::Epic => (root.join("docs/epics"), "E"),
        CreateKind::Design => (root.join("docs/designs"), "D"),
    };
    let id = id
        .map(str::to_string)
        .unwrap_or_else(|| allocate_id(root, prefix));
    let slug = title
        .to_ascii_lowercase()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .collect::<String>()
        .split('-')
        .filter(|s| !s.is_empty())
        .collect::<Vec<_>>()
        .join("-");
    let file = dir.join(format!("{id}-{slug}.md"));
    let body = match kind {
        CreateKind::Story => format!("---\nid: {id}\ntitle: {}\npillar: Core\nstatus: backlog\n{}{}---\n\n# {title}\n\n## Goal\n\n\n## Acceptance\n\n- [ ] Define acceptance.\n", yaml_quote(title), priority.map(|p|format!("priority: {p}\n")).unwrap_or_default(), epic.map(|v|format!("epic: {v}\n")).unwrap_or_default()),
        _ => format!("# {title}\n\n"),
    };
    if !command.dry_run {
        fs::create_dir_all(&dir)?;
        use std::io::Write;
        let mut output = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&file)
            .with_context(|| format!("conflict/precondition: {} already exists", file.display()))?;
        output.write_all(body.as_bytes())?;
    }
    Ok((
        format!(
            "created {id}{}",
            if command.dry_run { " (dry run)" } else { "" }
        ),
        json!({"id": id, "kind": format!("{kind:?}").to_ascii_lowercase(), "file": display_path(&file), "dry_run": command.dry_run, "content": if command.dry_run { Some(body) } else { None }}),
        vec![],
        changed_revision(root, command.dry_run)?,
    ))
}

fn allocate_id(root: &Path, prefix: &str) -> String {
    let max = read_stories(root)
        .unwrap_or_default()
        .iter()
        .filter_map(|s| {
            s.id.strip_prefix(&format!("{prefix}-"))
                .and_then(|n| n.parse::<u64>().ok())
        })
        .max()
        .unwrap_or(0);
    format!("{prefix}-{}", max + 1)
}

fn check_board(root: &Path) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let mut warnings = Vec::new();
    let stories = read_stories_with_warnings(root, &mut warnings)?;
    let mut errors = Vec::new();
    let mut ids = BTreeSet::new();
    for story in &stories {
        if !ids.insert(&story.id) {
            errors.push(format!("duplicate id {}", story.id));
        }
        if story.status == "ready" && story.priority.is_none() {
            errors.push(format!("{} is ready without integer priority", story.id));
        }
        if !story.file.starts_with(&story.id) {
            errors.push(format!("{} filename does not start with its id", story.id));
        }
    }
    if !errors.is_empty() {
        bail!("validation/gate: {}", errors.join("; "));
    }
    Ok((
        format!(
            "board valid: {} stories, {} warning(s)",
            stories.len(),
            warnings.len()
        ),
        json!({"valid": true, "stories": stories.len()}),
        warnings,
        None,
    ))
}

fn graph(
    command: &BoardCommand,
    root: &Path,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let stories = read_board_items(command, root)?;
    let nodes = stories
        .iter()
        .map(|s| json!({"ref": s.id, "status": s.status}))
        .collect::<Vec<_>>();
    let edges = stories
        .iter()
        .flat_map(|s| {
            s.dependencies
                .iter()
                .map(move |d| json!({"from": d, "to": s.id}))
        })
        .collect::<Vec<_>>();
    Ok((
        format!("{} node(s), {} edge(s)", nodes.len(), edges.len()),
        json!({"nodes":nodes,"edges":edges}),
        vec![],
        None,
    ))
}

