fn board_revision(root: &Path) -> Result<String> {
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    for story in read_stories(root).unwrap_or_default() {
        story.file.hash(&mut hasher);
        story.body.hash(&mut hasher);
    }
    for path in [
        root.join("docs/stories/README.md"),
        root.join("docs/vision.md"),
        root.join("docs/roadmap.md"),
        root.join("docs/VISION.md"),
        root.join("docs/ROADMAP.md"),
    ] {
        if let Ok(body) = fs::read_to_string(path) {
            body.hash(&mut hasher);
        }
    }
    Ok(format!("{:016x}", hasher.finish()))
}

fn scoped_board_revision(command: &BoardCommand, root: &Path) -> Result<String> {
    if command.scope != BoardScopeArg::Workspace {
        return board_revision(root);
    }
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    board_revision(root)?.hash(&mut hasher);
    let config = read_fleet_config(root)?;
    for repository in &config.repositories {
        repository.id.hash(&mut hasher);
        board_revision(&repository_root(root, repository)?)?.hash(&mut hasher);
    }
    Ok(format!("{:016x}", hasher.finish()))
}

fn changed_revision(root: &Path, dry_run: bool) -> Result<Option<String>> {
    if dry_run {
        Ok(None)
    } else {
        Ok(Some(board_revision(root)?))
    }
}
fn check_revision(expected: Option<&str>, actual: &str) -> Result<()> {
    if expected.is_some_and(|v| v != actual) {
        bail!("conflict/precondition: stale revision {expected:?}; current revision is {actual}");
    }
    Ok(())
}

fn yaml_quote(value: &str) -> String {
    format!("{:?}", value)
}

fn mutate_story(
    command: &BoardCommand,
    root: &Path,
    id: &str,
    fields: Vec<(&str, String)>,
    append: Option<(&str, &str)>,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let path = story_path(root, id)?;
    let body = fs::read_to_string(&path)?;
    let mut updated = body.clone();
    for (key, value) in &fields {
        updated = set_frontmatter(&updated, key, value)?;
    }
    if let Some((heading, text)) = append {
        updated.push_str(&format!("\n\n## {heading}\n\n- {text}\n"));
    }
    if !command.dry_run {
        fs::write(&path, &updated)?;
    }
    Ok((
        format!(
            "{id} updated{}",
            if command.dry_run { " (dry run)" } else { "" }
        ),
        json!({"id": id, "changed": updated != body, "dry_run": command.dry_run, "patch": if command.dry_run { Some(updated) } else { None }}),
        vec![],
        changed_revision(root, command.dry_run)?,
    ))
}

fn set_frontmatter(text: &str, key: &str, value: &str) -> Result<String> {
    if !text.starts_with("---") {
        bail!("validation/gate: story has no YAML frontmatter");
    }
    let mut lines = text
        .split_inclusive('\n')
        .map(str::to_string)
        .collect::<Vec<_>>();
    let end = lines
        .iter()
        .enumerate()
        .skip(1)
        .find_map(|(index, line)| (line.trim() == "---").then_some(index))
        .context("validation/gate: unclosed YAML frontmatter")?;
    let existing = (1..end).find(|index| {
        lines[*index]
            .split_once(':')
            .is_some_and(|(candidate, _)| candidate.trim() == key)
    });
    match (existing, value == "null") {
        (Some(index), true) => {
            lines.remove(index);
        }
        (Some(index), false) => lines[index] = format!("{key}: {value}\n"),
        (None, false) => lines.insert(end, format!("{key}: {value}\n")),
        (None, true) => {}
    }
    Ok(lines.concat())
}

fn complete_story(
    command: &BoardCommand,
    root: &Path,
    id: &str,
    override_reason: Option<&str>,
    changelog: Option<&str>,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let story = get_story(root, id)?;
    if !valid_planning_transition(&story.status, "done") {
        bail!(
            "conflict/precondition: planning transition {} -> done is not allowed",
            story.status
        )
    }
    let (_, remaining, _) = checkbox_counts(&story.body, "Acceptance");
    if remaining > 0 && override_reason.is_none() {
        bail!("validation/gate: {id} has {remaining} unchecked Acceptance criterion/criteria; pass --override-reason to record a reasoned override")
    }
    if override_reason.is_some_and(|reason| reason.trim().is_empty()) {
        bail!("input/schema: --override-reason cannot be empty")
    }
    let story_path = root.join("docs/stories").join(&story.file);
    let mut updated_story = set_frontmatter(&story.body, "status", "done")?;
    updated_story = set_frontmatter(&updated_story, "priority", "null")?;
    if let Some(reason) = override_reason {
        updated_story = set_frontmatter(&updated_story, "done_override", &yaml_quote(reason))?;
    }
    let changelog_path = root.join("CHANGELOG.md");
    let prior_changelog = fs::read_to_string(&changelog_path).ok();
    let updated_changelog = changelog.map(|entry| {
        add_unreleased_changelog_entry(prior_changelog.as_deref().unwrap_or("# Changelog\n"), entry)
    });
    if command.dry_run {
        return Ok((
            format!("would complete {id}"),
            json!({"id":id,"status":"done","dry_run":true,"story_patch":updated_story,"changelog_patch":updated_changelog,"override_reason":override_reason}),
            vec![],
            None,
        ));
    }

    let apply = (|| -> Result<()> {
        fs::write(&story_path, &updated_story)?;
        if let Some(updated_changelog) = &updated_changelog {
            fs::write(&changelog_path, updated_changelog)?;
        }
        render_track(root, false)?;
        Ok(())
    })();
    if let Err(error) = apply {
        let _ = fs::write(&story_path, &story.body);
        if updated_changelog.is_some() {
            if let Some(prior) = prior_changelog {
                let _ = fs::write(&changelog_path, prior);
            } else {
                let _ = fs::remove_file(&changelog_path);
            }
        }
        return Err(error.context("transaction: story completion rolled back authored files"));
    }
    Ok((
        format!("{id} completed"),
        json!({"id":id,"status":"done","dry_run":false,"changelog":changelog,"override_reason":override_reason}),
        vec![],
        changed_revision(root, false)?,
    ))
}

fn add_unreleased_changelog_entry(changelog: &str, entry: &str) -> String {
    let bullet = format!("- {entry}");
    if changelog.lines().any(|line| line == bullet) {
        return changelog.to_string();
    }

    const UNRELEASED: &str = "## [Unreleased]";
    const ADDED: &str = "### Added";
    let mut updated = changelog.to_string();
    if let Some(unreleased) = updated.find(UNRELEASED) {
        let section_start = unreleased + UNRELEASED.len();
        let section_end = updated[section_start..]
            .find("\n## ")
            .map(|offset| section_start + offset)
            .unwrap_or(updated.len());
        if let Some(added_offset) = updated[section_start..section_end].find(ADDED) {
            let insert = section_start + added_offset + ADDED.len();
            updated.insert_str(insert, &format!("\n\n{bullet}"));
        } else {
            updated.insert_str(section_start, &format!("\n\n{ADDED}\n\n{bullet}"));
        }
        return updated;
    }

    let prefix_end = updated
        .find('\n')
        .map(|index| index + 1)
        .unwrap_or(updated.len());
    updated.insert_str(
        prefix_end,
        &format!("\n{UNRELEASED}\n\n{ADDED}\n\n{bullet}\n"),
    );
    updated
}

fn transition(
    command: &BoardCommand,
    root: &Path,
    id: &str,
    status: &str,
    extra: Option<(&str, &String)>,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let status = normalize_status(status);
    if !STATUSES.contains(&status.as_str()) {
        bail!(
            "input/schema: planning status must be one of {}",
            STATUSES.join("|")
        );
    }
    let current = get_story(root, id)?.status;
    if !valid_planning_transition(&current, &status) {
        bail!("conflict/precondition: planning transition {current} -> {status} is not allowed");
    }
    let mut fields = vec![("status", status.clone())];
    if status != "ready" {
        fields.push(("priority", "null".into()));
    }
    if let Some((key, value)) = extra {
        fields.push((key, yaml_quote(value)));
    }
    mutate_story(command, root, id, fields, None)
}

fn valid_planning_transition(from: &str, to: &str) -> bool {
    from == to
        || matches!(
            (from, to),
            ("backlog", "ready")
                | ("ready", "in-progress")
                | ("ready", "blocked")
                | ("in-progress", "blocked")
                | ("in-progress", "done")
                | ("blocked", "ready")
                | ("blocked", "in-progress")
                | ("blocked", "done")
        )
}

fn append_story_section(
    command: &BoardCommand,
    root: &Path,
    id: &str,
    heading: &str,
    text: &str,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    mutate_story(command, root, id, vec![], Some((heading, text)))
}

struct CreateItemInput<'a> {
    kind: CreateKind,
    id: Option<&'a str>,
    title: &'a str,
    pillar: &'a str,
    status: &'a str,
    priority: Option<i64>,
    epic: Option<&'a str>,
    areas: &'a [String],
    design: Option<&'a str>,
    note: Option<&'a str>,
}

fn create_item(
    command: &BoardCommand,
    root: &Path,
    input: CreateItemInput<'_>,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let CreateItemInput {
        kind,
        id,
        title,
        pillar,
        status,
        priority,
        epic,
        areas,
        design,
        note,
    } = input;
    let status = normalize_status(status);
    if !matches!(status.as_str(), "backlog" | "ready") {
        bail!("input/schema: a new planning item status must be backlog or ready")
    }
    if status == "ready" && priority.is_none() {
        bail!("input/schema: a new ready story requires --priority")
    }
    if title.trim().is_empty() || pillar.trim().is_empty() {
        bail!("input/schema: title and pillar cannot be empty")
    }
    for area in areas {
        flux_datasource::board::BoardId::new(area)
            .map_err(|error| anyhow::anyhow!("input/schema: area {error}"))?;
    }
    let (dir, prefix) = match kind {
        CreateKind::Story => (root.join("docs/stories"), "C"),
        CreateKind::Epic => (root.join("docs/designs"), "E"),
        CreateKind::Design => (root.join("docs/designs"), "D"),
    };
    let id = id
        .map(str::to_string)
        .unwrap_or_else(|| allocate_id(root, prefix));
    let slug = title
        .to_ascii_lowercase()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .collect::<String>()
        .split('-')
        .filter(|s| !s.is_empty())
        .collect::<Vec<_>>()
        .join("-");
    let file = if kind == CreateKind::Epic {
        dir.join(format!("{slug}.md"))
    } else {
        dir.join(format!("{id}-{slug}.md"))
    };
    let body = match kind {
        CreateKind::Story => format!(
            "---\nid: {id}\ntitle: {}\npillar: {}\nstatus: {status}\n{}{}{}{}{}---\n\n# {title}\n\n## Goal\n\n\n## Acceptance\n\n- [ ] Define acceptance.\n",
            yaml_quote(title),
            yaml_quote(pillar),
            priority.map(|p|format!("priority: {p}\n")).unwrap_or_default(),
            epic.map(|value|format!("epic: {value}\n")).unwrap_or_default(),
            if areas.is_empty() { String::new() } else { format!("areas: [{}]\n", areas.join(", ")) },
            design.map(|value| format!("design: {value}\n")).unwrap_or_default(),
            note.map(|value| format!("note: {}\n", yaml_quote(value))).unwrap_or_default(),
        ),
        CreateKind::Epic => format!("# Design — {title}\n\n## Why\n\n\n## Approach\n\n\n## Stories\n\n"),
        CreateKind::Design => format!("# {title}\n\n## Why\n\n\n## Approach\n\n"),
    };
    if !command.dry_run {
        fs::create_dir_all(&dir)?;
        use std::io::Write;
        let mut output = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&file)
            .with_context(|| format!("conflict/precondition: {} already exists", file.display()))?;
        output.write_all(body.as_bytes())?;
    }
    Ok((
        format!(
            "created {id}{}",
            if command.dry_run { " (dry run)" } else { "" }
        ),
        json!({"id": id, "slug": slug, "kind": format!("{kind:?}").to_ascii_lowercase(), "file": display_path(&file), "status": status, "pillar": pillar, "areas": areas, "dry_run": command.dry_run, "content": if command.dry_run { Some(body) } else { None }}),
        vec![],
        changed_revision(root, command.dry_run)?,
    ))
}

fn allocate_id(root: &Path, prefix: &str) -> String {
    let max = read_stories(root)
        .unwrap_or_default()
        .iter()
        .filter_map(|s| {
            s.id.strip_prefix(&format!("{prefix}-"))
                .and_then(|n| n.parse::<u64>().ok())
        })
        .max()
        .unwrap_or(0);
    format!("{prefix}-{}", max + 1)
}

fn resolve_story_design(root: &Path, design: &str) -> Result<PathBuf> {
    let supplied = Path::new(design);
    if supplied.is_absolute() {
        bail!("permission: story design paths must be repository-relative")
    }
    let candidate = if design.starts_with("../") {
        root.join("docs/stories").join(supplied)
    } else if supplied.components().count() == 1 && supplied.extension().is_none() {
        root.join("docs/designs")
            .join(supplied)
            .with_extension("md")
    } else {
        root.join(supplied)
    };
    let canonical_root = root.canonicalize().with_context(|| {
        format!(
            "not-found: board root cannot be resolved at {}",
            root.display()
        )
    })?;
    let canonical = candidate
        .canonicalize()
        .with_context(|| format!("not-found: story design at {}", candidate.display()))?;
    if !canonical.starts_with(&canonical_root) || !canonical.is_file() {
        bail!(
            "permission: story design must be a file confined under {}",
            canonical_root.display()
        )
    }
    Ok(canonical)
}

fn check_board(root: &Path) -> Result<(String, Value, Vec<String>, Option<String>)> {
    check_board_with_known_dependencies(root, None)
}

fn check_board_with_known_dependencies(
    root: &Path,
    known_dependencies: Option<&BTreeSet<String>>,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let mut warnings = Vec::new();
    let stories = read_stories_with_warnings(root, &mut warnings)?;
    let mut errors = Vec::new();
    let mut ids = BTreeSet::new();
    for story in &stories {
        if !ids.insert(&story.id) {
            errors.push(format!("duplicate id {}", story.id));
        }
        if story.status == "ready" && story.priority.is_none() {
            errors.push(format!("{} is ready without integer priority", story.id));
        }
        if !story.file.starts_with(&story.id) {
            errors.push(format!("{} filename does not start with its id", story.id));
        }
        for dependency in &story.dependencies {
            if !stories.iter().any(|candidate| candidate.id == *dependency)
                && !known_dependencies.is_some_and(|known| known.contains(dependency))
            {
                errors.push(format!("{} depends on missing item {dependency}", story.id));
            }
        }
        if let Some(design) = story.design.as_deref() {
            if resolve_story_design(root, design).is_err() {
                errors.push(format!("{} links missing design {design}", story.id));
            }
        }
    }
    let decisions = decision_records(&root.join("docs/decisions"))?;
    let mut decision_ids = BTreeSet::new();
    for decision in &decisions {
        let id = decision["id"].as_str().unwrap_or_default();
        if !decision_ids.insert(id.to_string()) {
            errors.push(format!("duplicate decision id {id}"));
        }
        for blocked in decision["blocks"].as_array().into_iter().flatten() {
            let blocked = blocked.as_str().unwrap_or_default();
            if !stories.iter().any(|story| story.id == blocked) {
                errors.push(format!("decision {id} blocks missing item {blocked}"));
            }
        }
        if decision["status"].as_str() == Some("open") {
            if decision["question"].as_str().is_none_or(str::is_empty) {
                errors.push(format!("open decision {id} has no question"));
            }
            if let Some(recommended) = decision["recommended"].as_str() {
                let declared = decision["options"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .any(|option| option["id"].as_str() == Some(recommended));
                if !declared {
                    errors.push(format!(
                        "decision {id} recommends undeclared option {recommended}"
                    ));
                }
            }
        }
    }
    for roadmap in [root.join("docs/ROADMAP.md"), root.join("ROADMAP.md")] {
        if let Ok(body) = fs::read_to_string(&roadmap) {
            for target in markdown_link_targets(&body) {
                if target.starts_with("http:")
                    || target.starts_with("https:")
                    || target.starts_with('#')
                {
                    continue;
                }
                let target = target.split('#').next().unwrap_or_default();
                let resolved = roadmap.parent().unwrap_or(root).join(target);
                if !resolved.exists() {
                    errors.push(format!(
                        "roadmap {} links missing resource {target}",
                        roadmap.display()
                    ));
                }
            }
        }
    }
    if !errors.is_empty() {
        bail!("validation/gate: {}", errors.join("; "));
    }
    Ok((
        format!(
            "board valid: {} stories, {} warning(s)",
            stories.len(),
            warnings.len()
        ),
        json!({"valid": true, "stories": stories.len()}),
        warnings,
        None,
    ))
}

fn check_workspace_board(root: &Path) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let stories = workspace_stories(root)?;
    let known_dependencies = stories
        .iter()
        .map(|story| story.id.clone())
        .collect::<BTreeSet<_>>();
    let config = read_fleet_config(root)?;
    let mut members = BTreeMap::new();
    let mut warnings = Vec::new();
    for repository in &config.repositories {
        let member_root = repository_root(root, repository)?;
        let (_, data, member_warnings, _) =
            check_board_with_known_dependencies(&member_root, Some(&known_dependencies))?;
        warnings.extend(
            member_warnings
                .into_iter()
                .map(|warning| format!("{}: {warning}", repository.id)),
        );
        members.insert(repository.id.clone(), data);
    }
    Ok((
        format!(
            "workspace board valid: {} stories across {} member(s), {} warning(s)",
            stories.len(),
            members.len(),
            warnings.len()
        ),
        json!({"valid": true, "stories": stories.len(), "members": members}),
        warnings,
        None,
    ))
}

fn markdown_link_targets(body: &str) -> Vec<&str> {
    let mut targets = Vec::new();
    let mut rest = body;
    while let Some((_, after)) = rest.split_once("](") {
        let Some((target, tail)) = after.split_once(')') else {
            break;
        };
        targets.push(target.trim());
        rest = tail;
    }
    targets
}

fn graph(
    command: &BoardCommand,
    root: &Path,
) -> Result<(String, Value, Vec<String>, Option<String>)> {
    let stories = read_board_items(command, root)?;
    let nodes = stories
        .iter()
        .map(|s| json!({"ref": s.id, "status": s.status}))
        .collect::<Vec<_>>();
    let edges = stories
        .iter()
        .flat_map(|s| {
            s.dependencies
                .iter()
                .map(move |d| json!({"from": d, "to": s.id}))
        })
        .collect::<Vec<_>>();
    Ok((
        format!("{} node(s), {} edge(s)", nodes.len(), edges.len()),
        json!({"nodes":nodes,"edges":edges}),
        vec![],
        None,
    ))
}

